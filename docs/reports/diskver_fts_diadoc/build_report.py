paragraph('Конвертер УПД для Диадока. Автоматически получать уведомления о выкупе товара от Wildberries, разбирать их состав и преобразовывать в УПД с реквизитами Дисквер. Сохранить суммы выкупа, корректно рассчитать НДС и сформировать файл в формате, пригодном для загрузки в Диадок. Предоставить сотруднику экран выгрузки и учёта обработки документов.')

heading('2. Этапы и оценка трудоёмкости')
