def build(supplier_key, decisions=("matched",), limit=None, ids=None):
    """Строки файла импорта + замечания по каждой строке.

    `ids` — только эти строки новинок (кнопка «Это он» заводит карточку по одной строке;
    решение к этому моменту уже записано, поэтому фильтр по нему остаётся общим).
    """
    # Личность, а не профиль прайса: из профиля здесь берётся только `key` (аббревиатура кода
    # и карта габаритов), а кнопки «➕ В МС» / «Это он» работают и у поставщика без прайса.
    profile = get_identity(supplier_key)
    rows = query(
        """SELECT id, article, name, ms_code, price_rub, link
             FROM prc_novelty
            WHERE supplier_key = %s AND decision = ANY(%s) AND ms_code IS NOT NULL
              AND (%s::int[] IS NULL OR id = ANY(%s::int[]))
            ORDER BY id""",
        (profile.key, list(decisions), list(ids) if ids else None,
         list(ids) if ids else None))
    if limit:
        rows = rows[:limit]
    kin = family({(r["ms_code"] or "")[:4] for r in rows})
    # Эталон ресурса — каталог ТК: это описание МОДЕЛИ товара. Названия карточек родни
    # писали руками с прайсов РАЗНЫХ поставщиков, там разнобой и чужие комплектации
    # (под 6865 живёт архивная карточка Cactus на 20 000 стр. от другой модели вовсе).
    tk_pages = {r["external_code"]: r["resource"] for r in query(
        """SELECT external_code, resource FROM prc_tc_model
            WHERE gone_at IS NULL AND resource IS NOT NULL AND external_code = ANY(%s)""",
        (sorted({(r["ms_code"] or "")[:4] for r in rows}),))}
    # Вес каталога ТК — ПЕРВОИСТОЧНИК: ТК генерирует карточку товара, из неё вес уезжает на
    # площадки. Проверено 31.08.2026: на 6393 общих кодах вес ТК и вес карточки Озона совпали
    # до грамма у 6191 (96.8 %) — Озон эту величину получает, а не задаёт. Поэтому ТК идёт
    # раньше Озона, а Озон остаётся запасным на коды, которых в каталоге ТК нет.
    tk_weight = {r["external_code"]: r["weight_g"] for r in query(
        """SELECT external_code, weight_g FROM prc_tc_model
            WHERE gone_at IS NULL AND weight_g > 0 AND external_code = ANY(%s)""",
        (sorted({(r["ms_code"] or "")[:4] for r in rows}),))}
    oz = ozon_kin({(r["ms_code"] or "")[:4] for r in rows})
    known = {r["article"].strip().upper() for r in query(
        "SELECT article FROM ms_product WHERE article IS NOT NULL AND NOT archived")}
    tk_models, tk_titles = model_dict()

    records, notes = [], []
    for row in rows:
        row = dict(row, article=CARD_ARTICLE.get(profile.key, lambda a: a)(row["article"]))
        ext = (row["ms_code"] or "")[:4]
        cards = kin.get(ext) or []
        flags = []
        if not cards:
            notes.append((row["id"], row["article"], ["нет живой родни по внешнему коду — проверить код"]))
            continue
        path, path_all = _pick(
            cards, "path",
            keep=lambda p: p.startswith(GROUP_PREFIX) and not p.startswith(GROUP_SUPPLIER))
        code128, bc_all = _pick(cards, "code128")
        # «Название WB» — ТОЛЬКО по формуле из каталога ТК (правило 41; подтверждено
        # Сергеем 21.08.2026). На родню по этому полю не смотрим вовсе: там ручные
        # значения старого образца, и наследование их же и размножало. Замечание
        # выводим единственное — когда формула НЕ дала названия: пустое поле на
        # карточке недопустимо, его закрывает человек.
        wb, wb_flag = wb_compose(ext, row["name"])

        # Вес у родни расходится — берём САМУЮ СВЕЖУЮ карточку внешнего кода (решение
        # Сергея 08.08): её заводили последней, по последним данным.
        weighted = sorted((c for c in cards if c.get("weight")),
                          key=lambda c: c["created"], reverse=True)
        kin_weight = weighted[0]["weight"] if weighted else None
        weight_all = sorted({c["weight"] for c in weighted})

        # Первоисточник веса — прайс САМОГО поставщика по артикулу из прайса; дальше вес
        # родни в МС; в последнюю очередь — прайсы других поставщиков по кодам родни.
        own = DIMS_ARTICLE.get(profile.key, lambda a: a)(row["article"])
        weight, source = weight_from_dims([own], only=DIMS_SUPPLIER.get(profile.key))
        if weight and kin_weight and abs(weight - kin_weight) > 0.2 * max(weight, kin_weight):
            flags.append(f"вес поставщика {weight} против {kin_weight} у родни — взял поставщика ({source})")
        if not weight and kin_weight:
            weight = kin_weight
            source = (f"карточка {weighted[0]['code']}, заведена "
                      f"{weighted[0]['created']:%d.%m.%Y} — самая свежая по внешнему коду")
        if not weight:
            weight, source = weight_from_dims([c["article"] for c in cards])
        if not weight and tk_weight.get(ext):
            weight = round(float(tk_weight[ext]) / 1000, 3)
            source = f"каталог ТК, код {ext} — карточка товара платформы"
            flags.append(f"веса нет ни в прайсах, ни у родни — взял {weight} кг из каталога ТК")
        if not weight:
            grams = (oz.get(ext) or {}).get("weight_g")
            if grams:
                weight = round(float(grams) / 1000, 3)
                source = (f"карточка Озона {ext} ({oz[ext]['account']}) — ЗАЯВЛЕННЫЙ нами вес, "
                          f"не поставщика: проверить перед созданием")
                flags.append(f"веса нет ни в прайсах, ни у родни, ни в каталоге ТК — "
                             f"подставил {weight} кг: {source}")
            else:
                flags.append(source or "веса нет ни в прайсах поставщиков, ни у родни — "
                             "заполнить по nix.ru")

        if len(path_all) > 1:
            flags.append(f"группа у родни разная: {' / '.join(path_all)} → взял «{path}»")
        if len(bc_all) > 1:
            flags.append(f"штрихкод у родни разный: {' / '.join(bc_all)} → взял {code128}")
        if not code128:
            code128, why = ozon_barcode(oz, ext)
            if code128:
                flags.append(f"у родни нет Code128 — взял с карточки Озона "
                             f"{ext} ({oz[ext]['account']}): {code128}")
            else:
                flags.append(why or "у родни нет Code128 — заполнить вручную")
        if wb_flag:                            # и когда поле заполнено: сказать, откуда взято
            flags.append(wb_flag)
        if len(weight_all) > 1 and max(weight_all) > min(weight_all) * 1.2:
            flags.append(f"вес у родни расходится: {weight_all}, в файле {weight} — {source}")
        if row["price_rub"] is None:
            flags.append("нет цены в прайсе")
        if row["article"].strip().upper() in known:
            flags.append("артикул уже есть в МС — импорт по артикулу ПЕРЕПИШЕТ ту карточку")
        if row["link"]:
            flags.append(f"связь {row['link']} проставлена вручную — записал в «Связь»")
        # Сверяем ресурс из названия ПОСТАВЩИКА с эталоном (ТК, иначе родня) и допуском 25%
        # — тем же, что у сверки строки прайса с карточкой (`catalog.close`): поставщики
        # округляют («2.6K» = 2600 = 2500) и меряют по разным методикам.
        new_pages = name_resource(row["name"])
        ref, ref_src = tk_pages.get(ext), "в ТК"
        if not ref:
            kin_pages = sorted(p for p in (name_resource(c["name"]) for c in cards) if p)
            ref, ref_src = (kin_pages[-1] if kin_pages else None), "у родни"
        if close(new_pages, ref) is False:
            flags.append(f"ресурс в названии поставщика {new_pages} против {ref} {ref_src} "
                         f"(допуск {RESOURCE_TOLERANCE:.0%}) — по решению Сергея это норма, оставляем")
        # Модель КАРТРИДЖА из названия поставщика против модели внешнего кода в каталоге ТК.
        # Точнее сверки по принтерам: один принтер берёт десяток разных расходников, а
        # заголовок модели в ТК — это сам товар. Расхождение — почти всегда не та родня.
        model_diff = model_conflict(row["name"], ext, tk_models, tk_titles)
        if model_diff:
            flags.append(f"модель в названии поставщика {model_diff[0]} против {model_diff[1]} "
                         f"у кода {ext} в ТК — проверить, тот ли код")

        sup_id, sup_name = supplier_of(row["article"], profile, row["name"], path)
        records.append({
            # Служебное поле (не колонка файла): по нему после создания карточки строка
            # новинок получает свой итог. `write_xlsx` идёт по COLUMNS, лишний ключ ей не мешает.
            "_novelty_id": row["id"],
            "Группы": path or "",
            "Код": f"{ext}{suffix(row['article'], profile.key, row['name'])}",
            "Внешний код": ext,
            "Наименование": row["name"],
            "Описание": row["name"],
            "Артикул": row["article"],
            "Доп. поле: Код поставщика": row["article"],
            "Единица измерения": UOM,
            "Закупочная цена": float(row["price_rub"]) if row["price_rub"] is not None else "",
            "НДС": VAT,
            # Служебное: юрлицо-владелец карточки (у поставщика их несколько, см. supplier_of)
            "_supplier_id": sup_id,
            "Поставщик": sup_name,
            "Вес": weight or "",
            "Страна": COUNTRY,
            "Доп. поле: Гарантия/ Срок службы": WARRANTY,
            "Доп. поле: Название WB": wb or "",
            "Штрихкод Code128": code128 or "",
            "Доп. поле: Связь": row["link"] or "",
        })
        if flags:
            notes.append((row["id"], row["article"], flags))
    return records, notes


