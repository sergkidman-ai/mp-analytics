def suffix(article, supplier_key, name=""):
    """Аббревиатура поставщика для колонки «Код».

    У Одиссея White Box опознаётся по НАИМЕНОВАНИЮ (`is_white_box`), а не только по префиксу
    артикула: в прайсе метка стоит в названии, и артикул её иногда не несёт.
    """
    if supplier_key == "odissey" and is_white_box(name, article):
        return "wb"
    for pattern, abbr in NAME_SUFFIX.get(supplier_key, []):
        if re.search(pattern, name or "", re.IGNORECASE):
            return abbr
    for pattern, abbr in CODE_SUFFIX.get(supplier_key, []):
        if not pattern or re.search(pattern, article or "", re.IGNORECASE):
            return abbr
    raise KeyError(f"нет правила аббревиатуры кода для поставщика '{supplier_key}', "
                   f"артикул «{article}» — добавьте бренд в CODE_SUFFIX")


def supplier_of(article, profile, name="", path=""):
    """(id контрагента, имя) для новой карточки: юрлицо той же группы, что у родни бренда.

    У Одиссея на «ООО ОДИССЕЙ WB» сидят ДВА набора: бренд White Box (метка в наименовании)
    и вся струйка (категория МС, `is_inkjet`) — независимо от бренда. Аббревиатуру кода это
    не трогает: струйный Аквамарин остаётся `…at`, меняется только юрлицо.

    У Рапида (КВК ТРЕЙД) расклад тот же, но струйка считается только по обычной ветке
    (`kvk_inkjet`, правило 35): OEM-товар уезжает на юрлицо OEM по аббревиатуре `oem`,
    струйный SuperFine — по категории, и код у него остаётся `…sf`.
    """
    if profile.key == "odissey" and (is_white_box(name, article) or is_inkjet(path)):
        return SUPPLIER_BY_SUFFIX["odissey"]["wb"]
    if profile.key == "rapid" and kvk_inkjet(path):
        return SUPPLIER_BY_SUFFIX["rapid"]["oem"]
    if profile.key in SP_BY_TAIL:
        return SP_BY_TAIL["s_print_msk" if SP_MSK_TAIL.search(article or "") else "s_print_spb"]
    abbr = suffix(article, profile.key, name)
    found = SUPPLIER_BY_SUFFIX.get(profile.key, {}).get(abbr)
    if found:
        return found
    return profile.supplier_ids[0], MS_SUPPLIER.get(profile.key, profile.title)


def _attrs(payload):
    return {a.get("name"): a.get("value") for a in (payload.get("attributes") or [])}


def wb_name(value):
    """«Название WB» родни, приведённое к шаблону: «для» перед брендом принтера.

    В каталоге предлог стоит редко и местами слипся с моделью («106R03766для Xerox») —
    это ошибки заполнения, а не второй формат. Возвращает (название, замечание).
    Бренд не распознан — ничего не выдумываем, отдаём как есть с пометкой.
    """
    text = re.sub(r"\s+", " ", (value or "").replace(" ", " ")).strip()
    if not text:
        return "", None
    text = re.sub(r"(?<=[0-9A-Za-zА-Яа-я])(для)\b", r" \1", text, flags=re.IGNORECASE)
    text = re.sub(r"\bдля\b\s*", "для ", text, flags=re.IGNORECASE)
    match = BRAND_RE.search(text)
    if not match:
        return text, f"бренд принтера в «{text}» не распознан — «для» не поставлено"
    before = text[:match.start()].rstrip()
    if before.lower().endswith("для"):
        return text, None
    return f"{before} для {text[match.start():]}".strip(), None


# Цвет каталога ТК → слово в «Название WB». Смеси и редкие обозначения (BKM, PK…) сюда
# намеренно не включены: цвет там неоднозначен, а выдумывать слово нельзя — пропускаем.
TC_COLOR_WORD = {"BK": "черный", "C": "голубой", "M": "пурпурный", "Y": "желтый",
                 "GY": "серый", "LC": "светло-голубой", "LM": "светло-пурпурный",
                 "MK": "матовый черный"}
# «с чипом без счётчика» — это тоже С чипом (см. CHIP_MAP в collectors/thecartridge_catalog).
TC_CHIP_WORD = {"chip": "с чипом", "chip_free": "с чипом", "nochip": "без чипа"}
XL_RE = re.compile(r"\bxl\b|увеличен", re.IGNORECASE)


# Ресурс в хвосте названия поставщика («30K», «1.2K») и слова, которые моделью быть не могут.
RESOURCE_TOKEN = re.compile(r"^\d+([.,]\d+)?\s*[KККk]$")
HAS_DIGIT = re.compile(r"\d")


def tc_kinds():
    """Словарь типов расходника — из самого каталога ТК, своего списка не заводим."""
    return sorted({r["k"] for r in query(
        "SELECT DISTINCT raw->>'consumable_type' k FROM prc_tc_model"
        "  WHERE gone_at IS NULL AND raw->>'consumable_type' <> ''") if r["k"]},
        key=len, reverse=True)


CYRILLIC = re.compile(r"[А-Яа-я]")


def looks_like_model(text):
    """Модель — это КОД, а не кусок описания.

    Ограничитель нужен после разбора 26.08: у тонеров Cactus название начинается с бренда
    расходника и его артикула («Тонер Cactus CS-TKY3-870 черный флакон 870гр. для принтера
    Kyocera Universal TK-475»), и в «модель» уезжало «Cactus CS-TKY3-870 черный флакон 870гр.» —
    четыре РАЗНЫХ тонера (TK-475/4105/435/4145) получали одно имя, потому что артикул флакона
    у них общий. Код короток, содержит цифру и пишется латиницей; описание — нет.
    """
    words = text.split()
    return (1 <= len(words) <= 3 and len(text) <= 24
            and HAS_DIGIT.search(text) and not CYRILLIC.search(text))


def wb_from_price(price_name):
    """Сырьё формулы из НАЗВАНИЯ ПОСТАВЩИКА — когда каталога ТК по коду нет вовсе.

    Не пересказ имени (это отменённое «как у родни») и не выдумка: тип, модель, бренд, цвет
    и чип берутся ровно там же, где их берут шесть признаков сравнения, и складываются той же
    единственной формулой `wb_fill.compose`. Товара нет в ТК — но он есть у поставщика, и это
    честный источник. Чего в названии нет (чипа, цвета) — того и в поле не появится.

    Возвращает словарь формы каталога ТК либо None, если типа/модели/бренда не видно.
    """
    from prices import features
    name = re.sub(r"\s+", " ", price_name or "").strip()
    if not name:
        return None
    brands = features.brand(name)
    if len(brands) != 1:                       # два бренда в имени — какой из них наш, неясно
        return None
    head = name.split(",")[0]
    # Дефис границей слова НЕ считаем: иначе «Драм-картридж» и «Тонер-картридж» опознаются
    # как «Картридж», а в модель уезжает огрызок «Драм-». Нет типа в словаре ТК — отказ.
    edge = "А-Яа-яA-Za-z-"
    kind = next((k for k in tc_kinds()
                 if re.search(rf"(?<![{edge}]){re.escape(k)}(?![{edge}])", head, re.IGNORECASE)), "")
    if not kind:
        return None
    rest = re.sub(rf"(?<![{edge}]){re.escape(kind)}(?![{edge}])", " ", head, flags=re.IGNORECASE)
    left = re.split(r"(?<![А-Яа-яA-Za-z])для(?![А-Яа-яA-Za-z])", rest, flags=re.IGNORECASE)[0]
    for b in brands:                           # «Картридж Canon 054» -> модель «054»
        left = re.sub(rf"(?<![0-9A-Za-zА-Яа-я]){re.escape(b)}(?![0-9A-Za-zА-Яа-я])", " ", left,
                      flags=re.IGNORECASE)
    model = re.sub(r"\s+", " ", left).strip(" ,;-")
    if not looks_like_model(model):
        # «Тонер-картридж для Xerox DocuColor 240/250, 006R01449, Black, 30K» — модель за
        # запятой: первый кусок с цифрой, который не ресурс и не цвет.
        model = ""
        for seg in [x.strip() for x in name.split(",")[1:]]:
            if (seg and looks_like_model(seg) and " " not in seg
                    and not RESOURCE_TOKEN.match(seg) and not features.color(seg)):
                model = seg
                break
    if not model:
        return None
    color = features.color(name)
    chip = features.chip(name)
    return {"consumable_type": kind, "title": model, "additional_title": "",
            "printer_models": [{"brand": next(iter(brands))}],
            "ink_colors": [TC_COLOR_WORD[color]] if color in TC_COLOR_WORD else [],
            "chip": {"chip": "С чипом", "nochip": "Без чипа"}.get(chip, ""),
            "capacity": ""}


def wb_compose(external_code, price_name):
    """«Название WB» по формуле — единственный источник поля (правило 41).

    Формула на проект ОДНА и живёт в `tools/prc/wb_fill.py:compose()`; здесь только сырьё
    каталога ТК и признак XL из названия прайса (в каталоге ТК признак ПОСТАВКИ отсутствует).
    Своей копии формулы у конвейера больше нет (21.08.2026): копия отставала — в ней не было
    замены «Комплект …» → «Набор …», не бралось доп. название, бренд считался иначе, и у
    наборов в хвост лез перечень цветов. Две реализации одного правила расходятся молча.

    Каталог кода не знает или молчит о типе/модели/бренде — формула не отменяется, а меняет
    источник: то же сырьё берётся из названия поставщика (`wb_from_price`), и поле возвращается
    с замечанием «сверить». Пусто отдаём только если и там типа/модели/бренда не видно.
    """
    from tools.prc.wb_fill import compose      # импорт здесь: wb_fill тянет ATTRS из этого модуля
    rows = query("SELECT raw FROM prc_tc_model WHERE external_code = %s AND gone_at IS NULL",
                 (external_code,))
    if rows:
        name, why = compose(rows[0]["raw"])
        note = (f"каталог ТК по коду {external_code}: {why}" if not name else None)
    else:
        name, note = "", (f"каталога ТК по коду {external_code} нет" if external_code
                          else "строка не сведена с моделью каталога ТК")
    if not name:
        # Каталог молчит — собираем ту же формулу из названия поставщика (см. `wb_from_price`).
        raw = wb_from_price(price_name)
        name, why = compose(raw) if raw else ("", "в названии поставщика не видно типа/модели/бренда")
        if not name:
            return "", f"{note}; {why} — «Название WB» заполнить вручную"
        note = (f"{note} — «Название WB» собрано формулой из названия поставщика, "
                f"сверить модель и цвет")
    if XL_RE.search(price_name or "") and "XL" not in name.upper():
        name += " XL ресурс"                   # XL — признак поставки, он только в прайсе
    return name, note

UUID_EPOCH = datetime(1582, 10, 15)


def created_at(ms_id):
    """Когда карточка ЗАВЕДЕНА. Поля создания в API МС нет, но id — время-зависимый UUID:
    в нём лежит счётчик 100-нс от 1582-10-15 (сверено: карточка 08.08 → 08.08, документ
    оприходования 06.08 13:45 → 06.08 13:45). Не разобралось — считаем самой старой.
    """
    try:
        return UUID_EPOCH + timedelta(microseconds=UUID(str(ms_id)).time // 10)
    except (ValueError, AttributeError):
        return UUID_EPOCH


def family(codes):
    """Родня по внешнему коду: живые карточки МС со всем, что нужно новой карточке."""
    rows = query(
        """SELECT p.external_code ec, p.ms_id, p.code, p.article, p.name, p.updated_at,
                  r.payload payload
             FROM ms_product p JOIN raw_moysklad_product r ON r.ms_id = p.ms_id
            WHERE p.external_code = ANY(%s) AND NOT p.archived""",
        (list(codes),))
    out = {}
    for row in rows:
        payload, attrs = row["payload"], _attrs(row["payload"])
        code128 = next((b["code128"] for b in (payload.get("barcodes") or []) if b.get("code128")), None)
        weight = payload.get("weight")
        wb, wb_note = wb_name(attrs.get("Название WB"))
        out.setdefault(row["ec"], []).append({
            "code": row["code"], "article": row["article"], "name": row["name"],
            "updated": row["updated_at"], "created": created_at(row["ms_id"]),
            "path": payload.get("pathName"),
            "weight": float(weight) if weight else None, "code128": code128,
            "wb": wb or None, "wb_note": wb_note,
        })
    return out


# Префикс поставщика в артикуле: «CS-KMTNP80C» и «CR-KMTNP80C» — один и тот же товар
# у двух брендов одного завода. Отрезаем только префикс с разделителем, чтобы не съесть
# кусок кода модели («SACF226X» так и остаётся целым).
SUPPLIER_PREFIX = re.compile(
    r"^(?:CSP|CS|CR|GG|PR|GP|PL|HB|NP|NV|SF|OEM|TC|LX|SA|BS|BT|SL|EL|EP|T2|UT|UJ|UN|MY|IT|ML|ATM|SP|ST|AT|WB|SK)"
    r"[-_ ]", re.IGNORECASE)
_DIMS_CACHE = None


def _core(article):
    """Код модели без префикса поставщика и разделителей: CS-KMTNP80C -> KMTNP80C."""
    return re.sub(r"[^0-9A-Z]", "", SUPPLIER_PREFIX.sub("", str(article or "").upper()))


def weight_from_dims(articles, only=None):
    """Вес из прайсов поставщиков (`supplier_dims`) по кодам моделей.

    Это РЕАЛЬНЫЙ вес производителя, а не расчёт: тот же товар продаётся под кодами разных
    брендов одного завода (CS-KMTNP80C = CR-KMTNP80C). При расхождении больше 20% ничего
    не выбираем — пусть человек посмотрит. `only` ограничивает круг прайсов.
    """
    global _DIMS_CACHE
    cores = {c for c in (_core(a) for a in articles) if len(c) >= 6}
    if not cores:
        return None, None
    if _DIMS_CACHE is None:
        _DIMS_CACHE = [(r["supplier"], r["article"], float(r["weight_kg"]), _core(r["article"]))
                       for r in query("SELECT supplier, article, weight_kg FROM supplier_dims "
                                      "WHERE weight_kg IS NOT NULL AND weight_kg > 0")]
    hits = [h for h in _DIMS_CACHE if h[3] in cores and (only is None or h[0] in only)]
    if not hits:
        return None, None
    values = [h[2] for h in hits]
    if max(values) > min(values) * 1.2:
        return None, f"вес в прайсах поставщиков расходится: {sorted(set(values))} — проверить"
    best = max(hits, key=lambda h: h[2])
    return best[2], f"прайс {best[0]}, арт. {best[1]}"


def _pick(cards, field, keep=None, tie=None):
    """Значение поля у родни: что чаще; при равенстве — правило tie, иначе свежая карточка.

    keep отсеивает заведомо неподходящие варианты (чужая папка, кривое написание), но
    только если после отсева что-то осталось. Возвращает (значение, [все варианты] —
    в отчёт: расхождение внутри внешнего кода это вопрос к человеку, а не повод молчать).
    """
    values = [c[field] for c in cards if c.get(field) not in (None, "", 0)]
    if not values:
        return None, []
    counts = Counter(values)
    pool = [v for v in counts if keep(v)] if keep else list(counts)
    pool = pool or list(counts)
    top = max(counts[v] for v in pool)
    best = [v for v in pool if counts[v] == top]
    if len(best) == 1:
        chosen = best[0]
    elif tie:
        chosen = sorted(best, key=tie, reverse=True)[0]
    else:
        fresh = sorted((c for c in cards if c.get(field) in best),
                       key=lambda c: c["updated"] or date.min, reverse=True)
        chosen = fresh[0][field]
    return chosen, [v for v, _ in counts.most_common()]


# Карточка Озона — ЗАПАСНОЙ источник Code128 и веса, когда у родни в МС их нет вовсе.
# Штрихкод РОЖДАЕТСЯ в ТК и оттуда уезжает на площадки и в МС, но по API ТК его НЕ отдаёт
# (проверено 31.08.2026: `cartridge_models` — 31 поле, ни одного про штрихкод, маска
# `DS…` не встретилась ни разу на 200 моделях; `best` — только `buy_price`; `mix_data` — состав
# набора). Пока ТК не добавит поле (прецедент есть: `incoming_references` добавили по нашей
# просьбе 14.08.2026), карточка Озона — ближайшая к первоисточнику копия того же штрихкода.
# Случай Сергея 31.08.2026: строка ВТТ `HB-W2130X` сопоставлена с кодом 7025, а единственная
# карточка этого кода (`7025wb`) сама без веса и без штрихкода — наследовать нечего, и кнопка
# «➕ карточка поставщика» упиралась в два замечания без единого поля для ввода.
# Это не догадка и не расчёт: `offer_id` карточки Озона — наш же 4-значный внешний код,
# а штрихкод там наш собственный, той же маски DS+3 буквы+код (`7025` → `DSJUP0007025`).
# Замер 31.08.2026: 6380 штрихкодов на 6393 четырёхзначных кода, ни одного кода с двумя
# разными штрихкодами, и 13 штук с ЧУЖИМ кодом в хвосте — вот их брать нельзя, отсюда сверка
# хвоста ниже. Вес оттуда — наше же заявленное Озону значение, поэтому он идёт с пометкой
# и остаётся редактируемым в диалоге: подтверждает его человек, а не мы.
def ozon_kin(exts):
    """Внешний код → строка карточки Озона (`barcode`, `weight_g`, `account`)."""
    exts = sorted({e for e in exts if e})
    if not exts:
        return {}
    rows = query("""SELECT offer_id, barcode, weight_g, account FROM ozon_dims
                     WHERE offer_id = ANY(%s)
                     ORDER BY offer_id, (coalesce(barcode, '') = ''), account""", (exts,))
    out = {}
    for r in rows:                      # первая строка кода: сначала та, где штрихкод есть
        out.setdefault(r["offer_id"], r)
    return out


def ozon_barcode(oz, ext):
    """Штрихкод карточки Озона, если он ДЕЙСТВИТЕЛЬНО про этот код. -> (код, почему нет)."""
    r = oz.get(ext)
    bc = (r or {}).get("barcode") or ""
    if not bc:
        return None, None
    if not bc.endswith(ext):
        return None, f"штрихкод карточки Озона {bc} не про код {ext} — не беру, заполнить вручную"
    return bc, None


