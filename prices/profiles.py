# Короткие имена для командной строки: ключ профиля = имя группы в МС и может быть длиннее.
ALIASES = {"kaktus": "kaktus_msk"}


def get_profile(key):
    key = ALIASES.get(key, key)
    if key not in PROFILES:
        raise KeyError(f"нет профиля поставщика '{key}'; известные: {', '.join(sorted(PROFILES))}")
    return PROFILES[key]
