def get_identity(key):
    """Поставщик для ЗАВЕДЕНИЯ КАРТОЧКИ: профиль прайса, а если его нет — `IDENTITY`.

    Заведение карточки требует от поставщика только личности (`key`, `title`,
    `supplier_ids`), а не умения разбирать прайс. Разводим одно с другим, иначе поставщик
    без прайса не может попасть в МС из вкладки «Новинки».
    """
    if key in PROFILES:
        return PROFILES[key]
    if key in IDENTITY:
        return IDENTITY[key]
    raise KeyError(f"нет ни профиля прайса, ни личности поставщика '{key}'; "
                   f"известные: {', '.join(sorted(set(PROFILES) | set(IDENTITY)))}")


def get_profile(key):
    key = ALIASES.get(key, key)
    if key not in PROFILES:
        raise KeyError(f"нет профиля поставщика '{key}'; известные: {', '.join(sorted(PROFILES))}")
    return PROFILES[key]
