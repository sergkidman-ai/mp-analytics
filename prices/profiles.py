def norm(text):
    """Схлопнуть пробелы и регистр: 'больше 0 , но меньше 10' == 'Больше 0, но меньше 10'."""
    s = str(text or "").replace("\xa0", " ").strip().lower()
    s = re.sub(r"\s*,\s*", ", ", s)
    return re.sub(r"\s+", " ", s)


@dataclass
class Profile:
    key: str                      # ключ группы: он же префикс имени оприходования
    title: str                    # человеческое имя поставщика
    mail_folder: str              # IMAP-папка с прайсом (разделитель '|')
    columns: dict                 # логическое имя колонки -> заголовок в файле
    stock_map: dict               # нормализованный текст остатка -> количество
    currency: str = "RUB"         # валюта цен в прайсе
    markup: str = "1.00"          # надбавка к курсу ЦБ (Decimal-строкой)
    supplier_ids: list = field(default_factory=list)   # контрагенты группы в МС
    sheet: str = None             # имя листа; None — первый
    file_pattern: str = None      # регулярка на имя вложения: в письме может быть НЕСКОЛЬКО прайсов
    category: dict = field(default_factory=dict)       # логическое имя -> заголовок колонки-категории
    keep_categories: list = None  # None — грузим всё; иначе [(префикс группы, подгруппы|None)]
    header_scan_rows: int = 25    # в скольких верхних строках искать шапку
    header_span: int = 1          # на скольких подряд строках размазана шапка
    # Чип, если в названии о нём молчат: у одних поставщиков он есть всегда и потому
    # не упоминается (Кактус), у других молчание значит «неизвестно». None — не знаем.
    default_chip: str = None
    # Артикул поставщика, вынесенный в НАЗВАНИЕ товара. Колонка «Артикул» прайса и артикул
    # в наименовании расходятся («CS-TN-217» против «CS-TN217»), а карточка в МС заведена
    # то так, то эдак. То же правило работает на загрузке счетов — invoice_to_po.py:64.
    article_re: str = None
    # --- пороги проверки аномалий цены (строками: считаем в Decimal) ---
    # Коридор: живой минимум по трём прайсам 44.29 ₽, максимум 16 267 ₽ (05.08.2026).
    # Дно 20 ₽ ловит цену 1-2 ₽ (это заведомо аномалия) и не задевает самый дешёвый товар.
    price_min_rub: str = "20"
    price_max_rub: str = "200000"  # на порядок выше реального максимума
    jump_pct: str = "50"          # рост цены к нашей прошлой закупочной, % (решение Сергея 05.08)
    drop_pct: str = "50"          # падение цены, %
    shift_pct: str = "20"         # сдвиг МЕДИАНЫ всего прайса, % — признак смены колонки/валюты
    anomaly_share: str = "0.05"   # доля флагов от сопоставленных, выше которой --apply блокируется

    def qty(self, raw):
        """Остаток прайса -> число. None, если формулировка незнакома."""
        if raw is None:
            return None
        if isinstance(raw, (int, float)) and not isinstance(raw, bool):
            return float(raw) if raw > 0 else None
        text = norm(raw)
        if text in self.stock_map:
            return float(self.stock_map[text])
        # чистое число текстом ('12', '12,5')
        plain = text.replace(",", ".")
        if re.fullmatch(r"\d+(\.\d+)?", plain):
            value = float(plain)
            return value if value > 0 else None
        return None

    def keep_category(self, row):
        """Берём ли строку по её категории. True, если фильтр не задан.

        Правило: (префикс группы, только эти подгруппы | None, кроме этих подгрупп | None).
        Префикс, а не точное имя: «Совместимые для» покрывает все бренды разом, включая те,
        что поставщик заведёт завтра, — иначе новый бренд молча выпадет из загрузки.
        """
        if not self.keep_categories:
            return True
        group = norm(row.get("group"))
        subgroup = norm(row.get("subgroup"))
        for prefix, only, without in self.keep_categories:
            if not group.startswith(norm(prefix)):
                continue
            if only is not None and subgroup not in {norm(s) for s in only}:
                continue
            if without and subgroup in {norm(s) for s in without}:
                continue
            return True
        return False


