# Пишем серию так, как в файле матрицы: «ПРО» (решение Сергея 18.09.2026). В справочнике
# МоегоСклада значение сейчас называется «Про» — за совпадение отвечает `ms_import`, он ищет
# значение БЕЗ УЧЁТА РЕГИСТРА, поэтому переименование справочника в «ПРО» ничего не сломает.
SERIES = {"Комфорт": "Комфорт", "Бизнес": "Бизнес", "ПРО": "ПРО", "Про": "ПРО"}

# Формулы ячейки: «Бизнес» | «Бизнес до 5000/ ПРО» | «Комфорт до 600/ Бизнес/ ПРО от 4000».
# Порог включительно в нижнюю серию: «до 10000 — Бизнес, выше — ПРО» (примечание автора файла).
_TWO = re.compile(r"^(?P<low>[^ ]+) до (?P<edge>\d+)/\s*(?P<high>.+)$")
_THREE = re.compile(r"^(?P<low>[^ ]+) до (?P<edge1>\d+)/\s*(?P<mid>[^/]+?)/\s*(?P<high>[^ ]+) от (?P<edge2>\d+)$")


def kinds():
    """Типы расходника, для которых матрица знает серию, — список для формы."""
    return sorted(MATRIX)


def formula(kind, printer):
    """Ячейка матрицы для типа расходника и типа техники. -> строка формулы или None."""
    cells = MATRIX.get((kind or "").strip())
    if not cells:
        return None
    if "*" in cells:
        return cells["*"]
    return cells.get((printer or "").strip())


def series(kind, printer, price_rub):
    """(серия, пояснение). Серия = None, если матрица такой пары не знает.

    `price_rub` нужна только там, где в ячейке есть порог; для готовой серии цена не
    спрашивается — товар без цены всё равно получит серию.
    """
    cell = formula(kind, printer)
    if not cell:
        if not (kind or "").strip():
            return None, "тип расходника не определён"
        if not (printer or "").strip():
            return None, f"«{kind}»: не указан тип техники"
        return None, f"в матрице нет пары «{kind}» × «{printer}»"
    fixed = SERIES.get(cell)
    if fixed:
        return fixed, f"«{kind}»: серия {fixed} без порога"
    try:
        price = float(str(price_rub).replace(",", ".")) if str(price_rub).strip() else None
    except (TypeError, ValueError):
        price = None
    if price is None:
        return None, f"«{cell}» — нужна закупочная цена, а её нет"
    m = _THREE.match(cell)
    if m:
        low, mid, high = SERIES[m["low"]], SERIES[m["mid"].strip()], SERIES[m["high"]]
        edge1, edge2 = float(m["edge1"]), float(m["edge2"])
        got = low if price <= edge1 else (high if price >= edge2 else mid)
        return got, f"{price:.2f} ₽ по «{cell}» → {got}"
    m = _TWO.match(cell)
    if m:
        low, high = SERIES[m["low"]], SERIES[m["high"].strip()]
        got = low if price <= float(m["edge"]) else high
        return got, f"{price:.2f} ₽ по «{cell}» → {got}"
    return None, f"формулу «{cell}» разобрать не удалось"


# Догадка типа техники — ею заполняется поле в форме, человек её подтверждает или меняет.
# Сначала тип расходника (он однозначнее), потом слово в названии поставщика.
_BY_KIND = {
    "Чернила": "для струйного принтера", "Комплект чернил": "для струйного принтера",
    "Печатающая головка": "для струйного принтера", "СНПЧ": "для струйного принтера",
    "Лента для принтера": "для матричного принтера",
    "Краска полиграфическая": "для ризографа",
}
_BY_WORD = [
    (r"струйн|ink[-\s]?jet|снпч|чернил", "для струйного принтера"),
    (r"матричн|риббон", "для матричного принтера"),
    (r"сублимац", "для термосублимационного принтера"),
    (r"термотрансфер", "для термотрансферного принтера"),
    (r"ризограф", "для ризографа"),
    (r"\bфакс", "для факса"),
    (r"кассов|чеков", "для кассового оборудования"),
    (r"лазерн", "для лазерного принтера"),
]


def guess_printer(name, kind=""):
    """Тип техники по названию и типу расходника. Ничего не подошло -> лазерный.

    Лазерный по умолчанию не гадание вслепую: в каталоге ТК их 4685 против 1712 струйных
    и десятков всего прочего. Оператор видит подставленное значение и меняет, если не то.
    """
    by_kind = _BY_KIND.get((kind or "").strip())
    if by_kind:
        return by_kind
    text = str(name or "")
    for pattern, printer in _BY_WORD:
        if re.search(pattern, text, re.IGNORECASE):
            return printer
    return "для лазерного принтера"


# Названия, под которыми поставщик пишет тип, которого в словаре ТК нет дословно. Список
# короткий и только для СЕРИИ: «Название WB» живёт своими синонимами (`ms_import.KIND_SYNONYM`),
# и подмешивать туда наши догадки нельзя — там от типа зависит имя товара на площадке, а здесь
# лишь условное деление ассортимента. Проверено на очереди разбора: закрывает контейнеры Epson,
# наборы и риббон-картриджи — 35 строк из 438, которые иначе остались бы без серии.
KIND_SYNONYM = [
    (r"(?:комплект|набор)\s+тонер[-\s]?картридж", "Комплект картриджей"),
    (r"набор\s+картридж", "Комплект картриджей"),
    (r"набор\s+чернил", "Комплект чернил"),
    (r"контейнер\s+(?:с\s+)?чернил|ёмкость|емкость", "Чернила"),
    (r"риббон[-\s]?картридж", "Лента для принтера"),
]


def kind_of(name, external_code=""):
    """Тип расходника словами каталога ТК: сначала по коду из ТК, иначе из названия.

    Тот же разбор, что у «Названия WB» (`ms_import.wb_from_price`), — отдельного словаря
    видов не заводим.
    """
    from core.db import query
    from prices import ms_import
    ext = str(external_code or "").strip()
    if ext:
        rows = query("""SELECT raw->>'consumable_type' k FROM prc_tc_model
                         WHERE external_code = %s AND gone_at IS NULL
                           AND raw->>'consumable_type' <> '' LIMIT 1""", (ext,))
        if rows and rows[0]["k"]:
            return rows[0]["k"]
    head = re.sub(r"\s+", " ", str(name or "")).strip().split(",")[0]
    edge = "А-Яа-яA-Za-z-"
    for k in ms_import.tc_kinds():
        if re.search(rf"(?<![{edge}]){re.escape(k)}(?![{edge}])", head, re.IGNORECASE):
            return k
    for pattern, tk_kind in ms_import.KIND_SYNONYM + KIND_SYNONYM:
        if re.search(pattern, head, re.IGNORECASE):
            return tk_kind
    return ""
