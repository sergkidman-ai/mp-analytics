# поток: rev
"""Класс обращения покупателя — одна строка на запись в `raw_feedback.request_class`.

Зачем отдельный модуль, а не `feedback_corpus.intent()`: intent отвечает на вопрос «о чём речь»
(цвет, ресурс, установка) и нужен для подбора few-shot. Здесь другой вопрос — «чем это грозит,
если ответить машиной»: претензия после покупки требует человека всегда, независимо от темы.
Класс пишется и для ОТЗЫВОВ (у них до 07.09.2026 не было вообще никакой разметки), и для вопросов.

Порядок значим: сначала считается ОСНОВНОЙ класс по теме вопроса, затем правило A1.1
переопределяет его на «претензию». Переопределение вынесено после классификации 08.09.2026:
пока претензия проверялась первой, «сколько картриджей в комплекте? приехал один чёрный»
и «сколько в наборе?» были неразличимы — обе строки просто не доходили до тематических правил.
"""
import re

# Претензия/дефект/недостача — то, за чем стоит уже совершённая покупка и потери покупателя.
# Машинный ответ здесь либо бесполезен, либо (хуже) обещает деньги от лица компании: HP 953XL
# 03.09.2026 и Konica CMYK 31.08.2026 — оба про «оформим замену или возврат».
CLAIM_RX = re.compile(
    r"не\s+работ|не\s+печат|не\s+вид|не\s+распозна|не\s+опозна|не\s+определя|ошибк|брак|бракован|"
    r"дефект|неисправ|сломал|разбит|повреж|течёт|течет|подтек|полос|мажет|бледн|пятн|"
    r"не\s+подош|не\s+подход|не\s+совпад|друг(ой|ое|ая)\s+(товар|картридж|цвет)|пересорт|"
    r"недостач|не\s+хватает|не\s+доложил|не\s+положил|не\s+пришл|не\s+доехал|"
    r"вернуть|возврат|обмен|замен|компенс|деньги", re.I)
RULES = [
    # Порядок значим: первое совпадение выигрывает. «Заправка» стоит выше «характеристик», иначе
    # «чем заливать чернила» ушло бы в тип чернил, и выше «ресурса» — иначе «сколько мл
    # чернил заливать» посчиталось бы вопросом про ресурс (ревью Codex 08.09.2026);
    # «комплектация» выше «ресурса» по той же причине — «сколько картриджей в наборе».
    ("совместимость", r"подойд|подойт|подош[её]л|подход|совмест|встанет\s+ли|годится|для\s+модел|"
                      # 08.09.2026: неявные формы из docs/reports/rev_other_class_2026-09-08.md —
                      # покупатель не спрашивает «подойдёт ли», он утверждает и просит подтвердить.
                      r"это\s+(?:же\s+)?аналог|аналог\w*\s+(?:ли\s+)?карт|это\s+он\s+и\s+есть|"
                      r"вместо\s+картридж|использоваться\s+вместо|для\s+моего|для\s+моей|"
                      r"есть\s+ли\s+у\s+вас\s+.{0,40}(?:для|принтер)|нужен\s+картридж"),
    ("комплектация", r"комплект|в\s+набор|набор\w*\s+из|что\s+вход|"
                     r"сколько\s+(?:штук|шт\b|картридж|в\s+набор)"),
    ("заправка", r"заправ|дозапр|перезапр|перезаряж|снпч|чернил\w*\s+доли|"
                 r"зали(?:ть|вать)|лож\w*\s+чернил|класть\s+чернил|одноразов"),
    ("ресурс", r"ресурс|хват|стран|сколько\s+(?:печат|мл|грамм)|объ[её]м"),
    ("инструкция", r"как\s+(?:установ|вставл|снять|поставить|помест|прошить|сброс)|инструкц|не\s+знаю\s+как"),
    ("производитель", r"производител|кто\s+(?:делает|выпускает|изготав|производ)|"
                      r"кака[яй]\s+фирма|чь[её]\s+производств|товарн\w+\s+знак|бренд"),
    ("габарит", r"габарит|разм[ев]р|длин[аоуы]|ширин|высот|диаметр|сколько\s+см|помест(?:ит|ят)ся"),
    ("наличие", r"есть\s+ли\s+в\s+налич|когда\s+будет|привезёте|привезете|под\s+заказ"),
    ("доставка", r"доставк|привез|упаковк|коробк|помят|курьер|пвз"),
    ("характеристики", r"цвет|чип|оригинал|совместим\w*\s+чип|вес|состав|тонер\w*|"
                       # тип чернил и «новый или ref» — все формы из выгрузки «прочего» 08.09.2026
                       r"чернил|пигмент|водораствор|водорасвор|красител|драм\b|\bref\b|фотобараб|"
                       # гарантия КАК СВОЙСТВО товара (срок): поломка «по гарантии» уйдёт
                       # в претензию правилом A1.1 — оно переопределяет класс после этого списка
                       r"(?:кака[яй]|сколько|какой|есть\s+ли)\s+гаранти"),
]


# A1.1-fix (08.09.2026, бриф «претензия в форме вопроса»). Покупка уже совершена И описан отказ
# или расхождение с заявленным — это претензия, какой бы вежливой вопросительной формы она ни была.
# Два кейса Xerox C310 (docs/reports/rev_g0_flipped_2026-09-08.md) классификатор относил к «ресурсу»
# и «характеристикам»: «распечатала около 100 страниц и картридж оказался пустым. Как такое
# возможно?» — по теме это ресурс, по существу претензия, и машине её отдавать нельзя.
POSTBUY_RX = re.compile(
    r"куп(?:ил|ила|или)|заказ(?:ал|ала|али)|приобрел|получил|"
    r"пришл(?:о|а|и)\b|приш[её]л|приехал|привезл|доставил|"
    # «приходит ЛИ …» — вопрос о комплекте, а не факт покупки (ревью Codex 08.09.2026);
    # «второй раз мне уже приходит набор» — факт, и это претензия
    r"приход(?:ит|ят)(?!\s+ли)|"
    r"установил|установк\w*|поставил|вставил|заправил|распечатал|напечатал|отпечатал|"
    r"использовал|попробовал|вскрыл|отработал|проработал|хватило", re.I)
# Расхождение с заявленным или отказ товара.
MISMATCH_RX = re.compile(
    r"пуст(?:ой|ая|ое|ые|ым|ая)|не\s+соответств\w*|законч(?:ил|ились|илась)|"
    r"в\s+описании|на\s+фото|в\s+карточк|заявлен|обещан|вместо\s+(?:этого|заявленн)|"
    r"не\s+так(?:ой|ая|ие|ое)|не\s+тот\b|не\s+та\b|не\s+те\b|не\s+то\b|только\s+\d", re.I)
# Возмущение: само по себе означает, что покупатель уже столкнулся с проблемой.
OUTRAGE_RX = re.compile(
    r"как\s+так(?:ое|)\s+(?:возможно|может)|как\s+это\s+понимать|вы\s+серь[еёи]зн|"
    r"о\s+каких\s+\d|что\s+за\s+ерунд|это\s+нормальн", re.I)


# ОТРИЦАНИЕ ПЕРЕД МАРКЕРОМ ДЕФЕКТА (10.09.2026). Замер причин блоков показал: 3 из 10 «претензий»
# — отзывы 5★ Яндекса, где сработала подстрока в ПОХВАЛЕ: «Не полосит», «без полос», «нет ошибок».
# Детектор смотрел только на наличие подстроки. Гасим маркер, если прямо перед ним стоит отрицание.
_NEG_BEFORE_RX = re.compile(r"(?:\bне\b|\bнет\b|\bбез\b|\bни\b|никаки\w*)[\s,–-]{0,3}$", re.I)
# Гасится только маркер СОСТОЯНИЯ товара. Маркеры действия — «вернуть», «возврат», «обмен»,
# «замена», «компенсация», «деньги» — с отрицанием остаются претензией и даже усиливаются:
# «деньги не вернули», «замену не сделали».
_CANCELLABLE_RX = re.compile(
    r"^(?:ошибк|брак|бракован|дефект|неисправ|сломал|разбит|повреж|течёт|течет|подтек|"
    r"полос|мажет|бледн|пятн|пересорт|недостач)", re.I)


def _claim_marker(t):
    """Первый маркер претензии, не погашенный отрицанием. → совпадение или None."""
    for m in CLAIM_RX.finditer(t):
        if _CANCELLABLE_RX.match(m.group(0)) and _NEG_BEFORE_RX.search(t[:m.start()]):
            continue                      # «Не полосит», «без полос», «нет ошибок» — это похвала
        return m
    return None


# п.6 пакета 21.09.2026: претензия на КОМПЛЕКТАЦИЮ набора — «три цвета подошли, один не тот», «один
# короче», «один другой». Раньше такое шло как вопрос о комплекте, и движок подставлял связи
# номенклатуры (sku_relations) — фактически предлагал докупить (кейсы 0155 T0731, 0160 T0921).
_SET_ONE_RX = re.compile(r"\b(?:один|одна|одного|одной|одним)\b[^.!?]{0,30}?"
                         r"(?:не\s+т(?:от|а|ой|у)\b|короч|длинн|друг(?:ой|ая|ое|ого|ую)\b|"
                         r"не\s+подош|не\s+подход|не\s+встал|отлича)", re.I)
_SET_CTX_RX = re.compile(r"подош|подход|остальн|набор|комплект|цвет|встал", re.I)


# Тот же случай, названный цветом, а не «одним»: «жёлтый картридж короче, чем остальные три» (0160).
_SET_COLOR_RX = re.compile(r"(?:ж[её]лт|голуб|син|пурпур|красн|малин|ч[её]рн|цветн)\w*[^.!?]{0,40}?"
                           r"(?:короч|длинн|друг(?:ой|ая|ое|ого)\b|не\s+т(?:от|ой|а)\b|"
                           r"не\s+подош|не\s+встал|отлича)[^.!?]{0,40}?остальн", re.I)


def set_claim(text):
    """Претензия к составу набора: один из элементов не тот / другой / короче."""
    t = text or ""
    return bool((_SET_ONE_RX.search(t) and _SET_CTX_RX.search(t)) or _SET_COLOR_RX.search(t))


# Недостача и пересорт — тоже про ТЕКУЩИЙ товар, хотя в DEFECT_RX их нет: «недостача в комплекте» на 5★
# остаётся претензией. Исключение п.2 снимает только рассказы о прошлом и слова-действия без дефекта.
_SHORT_NOW_RX = re.compile(r"недостач|не\s+хватает|не\s+доложил|не\s+положил|не\s+пришл|не\s+доехал|"
                           r"пересорт|друг(ой|ое|ая)\s+(товар|картридж|цвет)", re.I)


def _defect_now(t):
    """Дефект или недостача ТЕКУЩЕГО товара. DEFECT_RX импортируем лениво: feedback_draft_run тяжелее."""
    from reports.feedback_draft_run import DEFECT_RX
    return bool(DEFECT_RX.search(t) or _SHORT_NOW_RX.search(t))


def is_claim_text(text, kind=None, rating=None):
    """Правило A1.1 отдельной функцией — его же зовёт publish_gate и тесты. Переопределяет ЛЮБОЙ
    тематический класс: тема вопроса тут вторична, важно, что за ним стоят потерянные деньги."""
    t = (text or "").strip()
    if not t:
        return False
    if set_claim(t):
        return True
    # п.2 пакета 21.09.2026: ложная претензия на позитиве. Отзыв ≥4★ без DEFECT_RX по текущему товару
    # претензией НЕ считаем: «были провалы уже» (4542) — про прошлые покупки, «заменила картридж
    # сама» (5418) — рассказ, не требование. Маркер действия «замен/возврат» в позитиве — не деньги.
    if kind == "review" and rating and rating >= 4 and not _defect_now(t):
        return False
    if _claim_marker(t):
        return True
    if kind == "review" and (rating or 5) <= 3:
        # низкая оценка с текстом без явного маркера — всё равно недовольство, машине не отдаём
        return True
    if OUTRAGE_RX.search(t):
        return True
    return bool(POSTBUY_RX.search(t) and MISMATCH_RX.search(t))


def classify(text, kind=None, rating=None):
    """→ строка класса. Пустой текст у отзыва — «оценка без текста», у вопроса — «прочее»."""
    t = (text or "").strip()
    if not t:
        return "оценка без текста" if kind == "review" else "прочее"
    base = "прочее"
    for name, rx in RULES:
        if re.search(rx, t, re.I):
            base = name
            break
    return "претензия" if is_claim_text(t, kind, rating) else base


def is_claim(cls):
    return str(cls or "") == "претензия"
