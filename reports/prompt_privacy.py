"""reports/prompt_privacy.py — что можно отдавать внешним моделям (правило Сергея 13.08.2026).

ПРАВИЛО. В промпты внешних LLM (Anthropic через relay, DeepSeek, веб-поиск) разрешены только:
  • данные, УЖЕ ОПУБЛИКОВАННЫЕ на витринах площадок (карточка WB/Ozon/Маркета: название, артикул
    площадки, характеристики, описание, список совместимости, наши листинги из каталога);
  • текст обращения покупателя (вопрос/отзыв, достоинства/недостатки) и его имя с площадки;
  • наши прошлые ОПУБЛИКОВАННЫЕ ответы (few-shot из справочника).
ЗАПРЕЩЕНО отдавать наружу что-либо финансовое и закупочное из МойСклада: закупочные цены,
себестоимость/COGS, поставщиков, маржу, наценку, остатки, обороты, продажи.
ВНУТРЕННИЕ СКЛАДСКИЕ ПОМЕТКИ (внутреннее название МС: «*ВНИМАНИЕ*», «White Box», «DS», «не идёт
в аппарат …», «уценка», «брак») видит ТОЛЬКО оператор в карточке модерации; в промпты моделей и в
тексты покупателю они не идут — инцидент 12.08.2026 с OKI C822, когда внутреннее предупреждение
ушло покупателю как «в карточке товара указано».

Здесь запрет живёт НА УРОВНЕ СБОРКИ ПРОМПТА, а не только в тексте системного промпта:
  public_name(...)        — имя товара без внутренних складских пометок (для промптов);
  assert_public_facts(...) — структурный стоп: в блок фактов попал финансовый/закупочный ключ;
  scrub_finance(...)      — текстовый стоп: вырезает предложение с финансовой/закупочной фактурой.
"""
import re

__all__ = ["PrivateDataInPrompt", "public_name", "assert_public_facts", "scrub_finance", "public_block"]


class PrivateDataInPrompt(Exception):
    """В сборку промпта пришло поле, которого не должно быть за пределами нашего контура."""


# Ключи МойСклада/витрин экономики, которых не должно быть в блоках фактов для модели.
FORBIDDEN_KEYS = frozenset({
    "buyprice", "saleprice", "minprice", "price", "prices", "cost", "costprice", "cogs",
    "purchase_price", "buy_price", "sale_price", "margin", "markup", "profit", "revenue",
    "turnover", "supplier", "supplier_name", "vendor_price", "stock", "stocks", "quantity",
    "qty", "balance", "reserve", "instock", "sales", "orders_sum", "закупка", "себестоимость",
    "маржа", "наценка", "остаток", "остатки", "поставщик", "оборот", "выручка",
})

# Внутренние складские пометки в названии МС. Якорим по маркеру, а не по «похоже на служебное»,
# чтобы не срезать реальную фактуру карточки (цвет, ресурс, серию).
_INTERNAL_MARK_RX = re.compile(
    r"\*(?=[^*\d])[^*]{0,60}\*"                        # *ВНИМАНИЕ*, *ПОД ЗАКАЗ* (не размеры 54*86*10)
    r"|(?<![\w-])White\s?Box(?![\w-])"                 # White Box (внутренняя категория упаковки)
    r"|(?<![\w-])DS(?![\w-])"                          # DS — внутренняя пометка (не модель DS-620)
    r"|не\s+идёт\s+в\s+аппарат[^,;.]*"                 # «Не идёт в аппарат C822»
    r"|не\s+ид[её]т\s+на[^,;.]*"
    r"|(?<![\w-])(?:уц[её]нк\w*|неликвид\w*|пересорт\w*|не\s+для\s+продажи|не\s+продавать)(?![\w-])",
    re.I)

# Финансовая/закупочная фактура в тексте. Слово «цена» намеренно НЕ ловим: покупатель про неё
# спрашивает, а витринная цена опубликована. Ловим то, что бывает только внутри контура.
_FINANCE_RX = re.compile(
    r"закупочн\w*|закупк\w*|себестоим\w*|\bCOGS\b|маржинальн\w*|\bмарж\w*|наценк\w*|"
    r"поставщик\w*|buyPrice|salePrice|minPrice|остаток\s+на\s+складе|остатки\s+склад\w*|"
    r"оборачиваем\w*|оборот\s+за|выручк\w*", re.I)


def public_name(name):
    """Имя товара для промпта: внутреннее складское название МС без служебных пометок."""
    s = _INTERNAL_MARK_RX.sub(" ", str(name or ""))
    s = re.sub(r"\(\s*\)|\[\s*\]", " ", s)
    s = re.sub(r"[ \t]{2,}", " ", s)          # переводы строк сохраняем: функция зовётся и на блоках
    return s.strip(" -–—,;")


def assert_public_facts(facts, where="prompt"):
    """Стоп-кран сборки: в словаре фактов для модели не должно быть финансовых/закупочных ключей.

    Срабатывает на изменение кода (кто-то расширил card_facts полем цены/остатка), а не на данные —
    поэтому падаем громко, а не молча вырезаем."""
    if not isinstance(facts, dict):
        return facts
    bad = sorted(k for k in facts if str(k).strip().lower() in FORBIDDEN_KEYS)
    if bad:
        raise PrivateDataInPrompt(
            f"{where}: в промпт внешней модели попали закрытые поля {bad} — разрешены только "
            f"опубликованные данные витрин и текст покупателя (см. reports/prompt_privacy.py)")
    return facts


def scrub_finance(text, where="prompt"):
    """Вырезает из НАШЕГО блока фактов предложения с финансовой/закупочной фактурой.

    Применять только к тому, что собираем мы (название, факты карточки, каталог) — НЕ к тексту
    покупателя: там слова «закупка/маржа» законны и вырезать их нельзя."""
    if not text:
        return text
    out, dropped = [], 0
    for src in str(text).split("\n"):           # построчно: блок фактов — это список пунктов
        kept, cut = [], 0
        for part in re.split(r"(?<=[.!?])\s+", src):
            if _FINANCE_RX.search(part):
                cut += 1
                continue
            kept.append(part)
        dropped += cut
        line = re.sub(r"[ \t]{2,}", " ", " ".join(kept)).strip()
        if cut and not line.strip(" -–—•"):     # пункт вырезан целиком — пустой маркер не оставляем
            continue
        out.append(line)
    if dropped:
        print(f"   prompt_privacy: {where} — вырезано предложений с закрытой фактурой: {dropped}",
              flush=True)
    return "\n".join(out).strip()


def public_block(text, where="prompt"):
    """Итоговый фильтр блока фактов перед отправкой модели: пометки + финансовая фактура."""
    return scrub_finance(public_name(text), where)
