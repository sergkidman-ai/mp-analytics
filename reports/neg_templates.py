# Два фильтра-приоритета (правило Сергея 10.09.2026). Они разбирают НЕ тип дефекта, а ситуацию,
# и потому проверяются ПЕРВЫМИ — раньше обычных типов и раньше правила «совпал ровно один»:
#   refill — товар заправляли. Что бы ни случилось потом, это результат заправки, а не картриджа;
#            отвечаем прямо, но без обвинений.
#   closed — покупатель уже избавился от товара (выкинул, разбил, вернул, купил другой). Помогать
#            нечем: любой шаблон здесь звучит издевательски. Черновик не подставляем, идёт человек.
# Только СОВЕРШЁННОЕ действие: «заправил», «заправляли», «после заправки». Прилагательное
# «перезаправляемый» — это свойство товара из вопроса о покупке, а не рассказ о заправке.
REFILL_RX = re.compile(
    r"(?:пере)?заправ(?:ил|ила|или|ля(?:л|ла|ли)|лен|лена|ляют)\w*|"
    r"(?:после|на|в)\s+(?:пере)?заправк\w*", re.I)
CLOSED_RX = re.compile(
    r"выкин\w*|выброс\w*|выбрас\w*|на\s+помойк|в\s+мусор|"
    # только АКТИВНОЕ действие покупателя: «разбил», «сломал». Возвратные формы («сломался»,
    # «разбилась») — это отказ товара, обычная жалоба, и закрывать её нечем
    r"(?:разбил|сломал)(?!ся|ась|ись|ось)\w*|"
    r"верн(?:ул|ула|ули)\w*|оформил\w*\s+возврат|сдал\w*\s+обратно|"
    r"купил\w*\s+(?:друг|в\s+друг|у\s+друг)\w*", re.I)

