def classify(text):
    """→ ключ типа жалобы, если совпал РОВНО один; иначе None (общий шаблон)."""
    t = text or ""
    hits = [k for k, rx in RULES if rx.search(t)]
    return hits[0] if len(hits) == 1 else None


def pick(text):
    """→ (тип, текст шаблона) или (None, None), если тип не определился однозначно."""
    k = classify(text)
    return (k, TEMPLATES[k]) if k else (None, None)
