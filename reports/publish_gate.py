"""Машинный вердикт «можно ли публиковать черновик покупателю».

Работа №1 из аудита 25.08.2026 (`/opt/mp-knowledge/auto-inbox/rev-qa-audit-2026-08-25.md`).
До неё сигналы недоверия (`grounded`, `confidence`, `no_card`, `code_guard`, `qa_guard`) писались
в `raw_feedback.draft_grounding`, но их не читала НИ ОДНА развилка публикации: 94 % черновиков
с маркером неуверенности уходили покупателю по ✅ оператора, публиковались ответы с conf 0.0.

Два класса причин, и порядок между ними важен (замечание независимого ревью):

* ЖЁСТКИЕ — детерминированные, посчитаны кодом: маршрут `human`, маркер-заглушка `⚠️`, пустая
  карточка (`no_card`), сработавший `code_guard`/`qa_guard`, ответ без источника (`source='модель'`).
  Им верим: это факты конвейера.
* МЯГКИЕ — то, что о себе сообщила сама языковая модель (`grounded`, `confidence`). Им верим
  меньше, и строить на них вердикт в одиночку нельзя — но для запрета публикации их достаточно,
  запрет всегда в сторону «не отправлять».

Вердикт НЕ хранится в БД: он чистая функция от строки `raw_feedback` и пересчитывается на каждом
обращении. Отдельная колонка причины эскалации — работа №4, здесь не нужна.
"""
import json
import os
import re

from reports import request_class as rc

MIN_CONF = float(os.getenv("FEEDBACK_MIN_CONF", "0.6"))

# Очередь 46 (10.09.2026), п.3. Классы, где ответ целиком лежит в карточке или в утверждённом
# кэше: свойство товара, производитель, состав набора, размер. Там нечего «обосновывать» — факт
# либо есть в карточке, либо его нет, и самооценка модели (grounded/confidence) к делу не
# относится. Замер за 14 дней: из 14 блоков по confidence добрая половина — ответы, верные по
# карточке (docs/reports/rev_block_reasons_2026-09-10.md).
# Совместимость входит сюда ТОЛЬКО при точном совпадении модели со списком карточки — семейное
# совпадение подстроки (дефект A1) и справочник сюда не относятся.
CARD_CLASSES = ("характеристики", "производитель", "комплектация", "габарит")

# Причины, которые кнопкой «Отправить как есть» не обходятся (п.1): обещание от лица компании
# и претензия. Первое движок не вправе давать вообще, второе — разговор с недовольным человеком,
# и подписываться под машинным текстом там нельзя. Оператор отвечает через «Править».
# Маркер-заглушка добавлен к этим двум не как исключение, а по смыслу кнопки: «отправить как
# есть» отправляет ТЕКСТ ЧЕРНОВИКА, а «⚠️ на человека» — не текст ответа, и покупателю он уйти
# не может физически.
NO_OVERRIDE = ("обещание в черновике", "претензия, ручной ответ",
               "маркер-заглушка")


def _card_sourced(g):
    """Источник ответа — карточка или утверждённый оператором кэш (не веб, не «модель»)."""
    src = str(g.get("source") or "")
    if src.startswith("кэш"):
        return "веб" not in src                    # «кэш(веб)» — это вчерашний веб, не карточка
    return src.startswith("карточка") and not src.startswith("карточка-серия")


# Шаблоны-хендоффы негатива (reports/feedback_draft_run.py): «нам жаль, напишите в чат по QR».
# Утверждений о товаре и обещаний в них нет — они только переводят разговор в личный канал.
_HANDOFF_TPL = ("neg_type:", "neg_general_wb", "neg_general_oz", "dead_card")


# Признаки хендоффа в СВОБОДНОМ тексте (черновики претензий пишет LLM, template_id у них 'llm').
_HANDOFF_RX = re.compile(r"чат\s+по\s+QR|QR-?\s?код|напишите\s+(?:нам\s+)?в\s+чат", re.I)
# Вердикт о причине поломки. Движок не вскрывал этот картридж и знать причину не может; такое
# утверждение в публичном ответе — признание вины магазина (черновик mod=652, 12.09.2026:
# «это явно производственный дефект»). Даже чистый в остальном хендофф с этим не публикуем.
_VERDICT_RX = re.compile(r"производственн\w*\s+(?:дефект|брак)|заводск\w*\s+брак|это\s+брак|"
                         r"явн\w*\s+(?:дефект|брак)|наша\s+вина|подтвержда\w+\s+(?:дефект|брак)", re.I)


def _safe_handoff(g, own_draft, body):
    """Узкое исключение к A1.1 (решение Сергея 12.09.2026): претензия + НЕТРОНУТЫЙ шаблон-хендофф
    = кнопка ✅ доступна, оператор решает сам.

    Почему это не дыра в правиле A1.1. Запрет стоит затем, что ответ на претензию — обязательство
    перед конкретным человеком, а движок не знает, что случилось с ЭТИМ экземпляром. Хендофф
    ничего не утверждает и ничего не обещает: он зовёт в чат, где разбирается человек. Условий
    три, и снимается запрет только при всех сразу:
      1. own_draft — текст ровно наш шаблон. Правка оператора судится на общих основаниях
         (та же логика, что у dead_card с 08.09.2026).
      2. template_id из списка хендоффов. Ответ, собранный LLM или кэшем, сюда не попадает.
      3. в тексте нет слов-обещаний (PROMISE_RX) — страховка на случай правки самих шаблонов.
    Остальные причины гейта (no_card, code-guard, qa-guard, устаревший кэш, D1 о совместимости)
    считаются отдельно и этим исключением не снимаются."""
    if not own_draft:
        return False
    if PROMISE_RX.search(body) or _VERDICT_RX.search(body):
        return False
    tpl = str(g.get("template_id") or "")
    if any(tpl == t or (t.endswith(":") and tpl.startswith(t)) for t in _HANDOFF_TPL):
        return True
    # Черновик написан моделью (template_id='llm'): хендоффом считаем только короткий текст,
    # который зовёт в чат и ничего не утверждает. 600 знаков — предел сожаления с приглашением;
    # длиннее начинаются разборы причин, а их публиковать без человека нельзя.
    return bool(_HANDOFF_RX.search(body)) and len(body.strip()) <= 600


def eased_class(row, g=None, cls=None):
    """Класс, для которого мягкие сигналы и guard полярности не применяются (п.3). → bool."""
    if row.get("kind") != "question":
        return False
    g = _ground(row) if g is None else g
    if cls is None:
        cls = (g.get("request_class") or row.get("request_class")
               or rc.classify(_customer_text(row), kind="question", rating=row.get("rating")))
    if cls in CARD_CLASSES:
        return _card_sourced(g)
    if cls == "совместимость":
        # точное совпадение: спрошенные модели все до одной названы в списке карточки
        c = g.get("compat") if isinstance(g.get("compat"), dict) else None
        asked = list((c or {}).get("asked") or [])
        matched = list((c or {}).get("matched") or [])
        return bool(asked) and all(a in matched for a in asked) and _card_sourced(g)
    return False


# ТРЕЙС-ONLY ДЛЯ ВОПРОСОВ (10.09.2026, распоряжение Сергея после разбора очереди 46).
# Замер причин блоков за 14 дней (docs/reports/rev_block_reasons_2026-09-10.md) показал: на
# вопросах самостоятельной ценности не имеют ни D1/D3–D6, ни A1.3, ни grounded/confidence, ни
# полярность, ни «подстрока в серии» (дефект A1) — под верными блоками всегда стояла одна из
# трёх настоящих причин. Остальное держало в очереди готовые ответы. Поэтому для kind=question
# запрет оставлен ровно за тремя: стоп-лист обещаний A1.2, класс «претензия», маркер-заглушка
# (+ маршрут human — там черновика нет вовсе, отправлять физически нечего).
# Причины НЕ удалены: они по-прежнему считаются и возвращаются третьим элементом verdict_full()
# — идут в трейс карточки и в лог отправки, но кнопку ✅ не снимают. ОТЗЫВОВ НЕ КАСАЕТСЯ.
# Выключается флагом FEEDBACK_Q_TRACE_ONLY=0 (вернёт прежнее поведение целиком).
Q_TRACE_ONLY = os.getenv("FEEDBACK_Q_TRACE_ONLY", "1") != "0"

# D3 (ссылка на парный лот только со справочником) выключен 10.09.2026 целиком — и для вопросов,
# и для отзывов: подстановка нашего артикула вернулась к поведению до 08.09.
D3_ENABLED = os.getenv("FEEDBACK_D3", "0") == "1"
Q_BLOCKING = NO_OVERRIDE + ("маршрут human",)


def split_trace(reasons, kind):
    """→ (блокирующие, трейс-only). Для отзывов и при выключенном флаге трейс пуст."""
    if kind != "question" or not Q_TRACE_ONLY:
        return list(reasons), []
    hard = [r for r in reasons if r.startswith(Q_BLOCKING)]
    return hard, [r for r in reasons if not r.startswith(Q_BLOCKING)]


def can_override(reasons):
    """Можно ли показать «✅ Отправить как есть» (п.1). Пустые причины = кнопка и так обычная ✅."""
    return bool(reasons) and not any(r.startswith(NO_OVERRIDE) for r in reasons)

# A1.2 (07.09.2026). Обещание от лица компании в МАШИННОМ черновике — запрет независимо от класса
# обращения: движок не знает ни условий возврата, ни остатка на замену. Реальные случаи — HP 953XL
# 03.09.2026 и Konica CMYK 31.08.2026, оба «оформим замену или возврат». К тексту, который написал
# оператор, стоп-лист НЕ применяется (см. verdict: судим только собственный черновик).
#
# Список из брифа (`возврат|замен|компенс|…`) прогнан по 344 черновикам за 30 дней и СУЖЕН: голое
# «замен»/«возврат» ловит техническую речь, к обязательствам не относящуюся — «замена чипа простая»,
# «надёжнее заменить на новый», «подскажем, как оформить возврат». Ловим то, что компания обещает
# СДЕЛАТЬ: глагол в первом лице мн. ч. либо конструкция обязательства («решим вопрос заменой»).
PROMISE_RX = re.compile(
    # «вернём» без хвоста: «вернёмся с ответом» — не обещание возврата (замечание ревью 08.09).
    r"верн[ёе]м(?!ся)|возместим|компенсируем|заменим|обменяем|дошл[её]м|дошлем|вышлем|оформим|"
    r"гарантируем|поможем\s+с\s+(?:возврат|замен|обмен)|"
    r"реш\w+\s+(?:вопрос|это|его|её|ее)?\s*[^.!?]{0,40}?(?:замен|возврат|обмен)|"
    r"за\s+наш\s+сч[ёе]т|бесплатн\w*\s+(?:замен|отправ|вышл|доставк|обмен)", re.I)

# A1.3. Утвердительный ответ о совместимости. «не подойдёт» — не утверждение, а отказ, его пропускаем.
# Голого «Да» в начале мало: движок пишет и «Да, к сожалению, не подойдёт» — поэтому зачин считается
# утверждением только при отсутствии отказа в тексте, а прямое «подойдёт» (FIT_RX уже с оглядкой
# на «не»/«нет») достаточно само по себе даже в смешанном ответе (замечание ревью 08.09.2026).
YES_RX = re.compile(r"^\s*(?:здравствуйте[!,.]?\s*)?(?:да\b|конечно\b)", re.I)
FIT_RX = re.compile(r"(?<!не )(?<!нет )\b(подойд[её]т|подойдут|подходит|подходят|совместим)", re.I)
NO_FIT_RX = re.compile(r"\bне\s+(?:подойд[её]т|подойдут|подходит|подходят|совместим\w*)|несовместим", re.I)


def _dead_text():
    """Текст хендоффа по «мёртвой» карточке. Импорт ленивый: card_rating тянет за собой БД, а гейт
    обязан оставаться чистой функцией и работать в тестах офлайн."""
    try:
        from reports.card_rating import DEAD_TEXT
        return DEAD_TEXT.strip()
    except Exception:
        return "\0"


def _customer_text(row):
    """Текст ПОКУПАТЕЛЯ (не черновика) — для класса обращения на строках, драфтнутых до 07.09.2026."""
    if row.get("kind") == "review":
        return " ".join(filter(None, [row.get("body"), row.get("pros"), row.get("cons")]))
    return row.get("body") or ""


def _same(a, b):
    """Тексты «те же» с точностью до регистра и пробелов — сравнение черновика с отправляемым."""
    return " ".join((a or "").split()).casefold() == " ".join((b or "").split()).casefold()


def _ground(row):
    g = row.get("draft_grounding")
    if isinstance(g, str):
        try:
            g = json.loads(g)
        except Exception:
            g = None
    return g if isinstance(g, dict) else {}


def verdict(row, text=None):
    """→ (allow: bool, reasons: list[str]) — только блокирующие причины (см. split_trace)."""
    allow, reasons, _trace = verdict_full(row, text)
    return allow, reasons


def verdict_full(row, text=None):
    """→ (allow, reasons, trace). Пустой список reasons = публиковать можно; trace — причины,
    посчитанные, но публикацию не держащие (вопросы, см. split_trace): их место в карточке и логе.

    text — фактический текст к отправке; если он отличается от черновика, значит его писал человек,
    и судить машинными сигналами о черновике уже нечего (вызывающий обязан пометить это override).
    """
    reasons = []
    kind = row.get("kind")
    g = _ground(row)
    body = (text if text is not None else row.get("draft_text")) or ""

    # --- жёсткие: детерминированные факты конвейера ---
    if row.get("draft_route") == "human":
        reasons.append("маршрут human (домен-фильтр или битый JSON модели)")
    if body.strip().startswith("⚠️"):
        reasons.append("маркер-заглушка «на человека», это не ответ покупателю")
    if g.get("no_card"):
        reasons.append("нет данных карточки — ответ собран по каталогу/вебу")
    if g.get("code_guard"):
        reasons.append("code-guard вырезал код расходника, которого нет ни в карточке, ни в вопросе")
    # eased (п.3, 10.09.2026): класс, чей ответ целиком в карточке. Для него не применяем
    # самооценку модели и пометку полярности — см. CARD_CLASSES.
    eased = eased_class(row, g)
    if g.get("qa_guard"):
        qa = g.get("qa_guard")
        qa = list(qa) if isinstance(qa, (list, tuple)) else [str(qa)]
        if eased:
            # Снимаем пометку только там, где guard ТЕКСТ НЕ МЕНЯЛ. С 10.09.2026 он не меняет его
            # никогда («текст не изменён»), но в БД остались строки, драфтнутые старым guard'ом:
            # у них голое «не прямой ответ» означает, что «Да,»/«Нет,» ВПИСАНО в ответ машиной и
            # смысл мог сломаться («Нет, технически заправить можно»). Такие не публикуем.
            qa = [x for x in qa
                  if not ("текст не изменён" in str(x) or "полярность не определена" in str(x))]
        if qa:
            det = ", ".join(map(str, qa))[:120]
            reasons.append(f"qa-guard: {det}")
    # G (08.09.2026): подстановка из кэша утверждённых ответов, у которой карточка успела
    # измениться по полю из ключа (совместимость или атрибут). Текст был верен на момент
    # утверждения — публиковать его сейчас нельзя, оператор смотрит глазами.
    cache = g.get("cache") if isinstance(g.get("cache"), dict) else None
    if cache and cache.get("stale"):
        reasons.append("кэш устарел: карточка изменилась после утверждения ответа")

    # Текст оператора (text ≠ черновик) — не наш черновик: сравниваем без регистра и лишних
    # пробелов, иначе смена одной заглавной буквы объявляла машинный текст «правкой человека».
    own_draft = text is None or _same(text, row.get("draft_text"))

    # A1.1: претензия / дефект / недостача — только ручной ответ, чем бы черновик ни был обоснован.
    # Класс пишет _store() с 07.09.2026; на строках старше считаем его тут же по тексту покупателя.
    # Исключение одно — «мёртвая» карточка: там уходит сухой хендофф по правилу Сергея 24.08.2026,
    # и держать его = вечно копить в очереди отзывы по карточке, которую всё равно снимают.
    cls = g.get("request_class") or rc.classify(_customer_text(row), kind=kind, rating=row.get("rating"))
    # Исключение сужено (ревью 08.09.2026): template_id снимает запрет только с НЕТРОНУТОГО
    # черновика — отредактированный текст под тем же шаблоном судим на общих основаниях.
    dead = (g.get("template_id") == "dead_card" and own_draft) or body.strip() == _dead_text()
    # A1.1-fix (ревью Codex 08.09.2026): сохранённый класс мог быть посчитан ДО правки
    # классификатора («ресурс» у пары Xerox C310), поэтому признак претензии считаем по тексту
    # покупателя независимо от него. Правило только ужесточает: снять запрет оно не может.
    claim = rc.is_claim(cls) or rc.is_claim_text(_customer_text(row), kind, row.get("rating"))
    if claim and not dead and not _safe_handoff(g, own_draft, body):
        reasons.append("претензия, ручной ответ")

    # A1.2: обещание в СОБСТВЕННОМ черновике. Текст оператора не судим — он отвечает за свои
    # слова сам, и запрещать человеку слово «замена» движок не вправе.
    if own_draft:
        m = PROMISE_RX.search(body)
        if m:
            reasons.append(f"обещание в черновике: «{m.group(0)}»")

    # D1 (блок D, 08.09.2026). Источников утвердительного «да» о совместимости ровно два:
    # список совместимости карточки и справочник compat_ref. Веб — НЕ источник: ровно через него
    # пришли Epson C5890 (T945x, за картридж принято тело ПЗК), Canon LBP646 (выдуманная серия
    # 075H), HP 4303 («спецификация HP 212A») и Epson 680 (T026 вместо T017).
    # Правило шире прежнего A1.3 в двух местах: справочник добавлен вторым законным источником,
    # и на вебе запрещён также ОТРИЦАТЕЛЬНЫЙ ответ по неподтверждённой модели — отказ по LBP646
    # был верен, но допродажа в том же тексте выдумана. Судим по тексту черновика и следу
    # совместимости, а не по классу: класс ловит и неявные формулировки, а трейс есть у любого
    # вопроса с моделью. compat пишет feedback_today.py; без него правило молчит.
    source = str(g.get("source") or "")
    compat = g.get("compat") if isinstance(g.get("compat"), dict) else None
    if compat and compat.get("asked"):
        asked_all = list(compat.get("asked") or [])
        matched = list(compat.get("matched") or [])
        ref_ok = compat.get("ref_matched")
        if ref_ok is None:            # строка старше блока D — спрашиваем справочник сами
            try:
                from reports import compat_ref
                ref_ok = compat_ref.confirms(asked_all, compat.get("series"))[0]
            except Exception:
                ref_ok = []           # справочник молчит → подтверждения нет, гейт закрывается
        unconfirmed = [a for a in asked_all if a not in matched and a not in (ref_ok or [])]
        affirm = FIT_RX.search(body) or (YES_RX.search(body) and not NO_FIT_RX.search(body))
        web_based = bool(g.get("web")) or "веб" in source
        who = ", ".join(map(str, unconfirmed))[:80]
        if web_based:
            # веб — черновик оператору ВСЕГДА, независимо от знака ответа: отказ по LBP646 был
            # верен, а допродажа в том же тексте выдумана, и разделить их гейт не может.
            reasons.append("D1: ответ о совместимости построен на вебе"
                           + (f", модель {who} не подтверждена карточкой или справочником" if who else ""))
        elif unconfirmed and affirm:
            reasons.append(f"D1: «да» о совместимости без карточки и справочника (модель {who})")
        # D4: ресурсные версии вниз не совместимы (OKI, Kyocera, HP LaserJet). Справочник знает
        # эту модель под ДРУГИМ вариантом той же серии — ответ обязан назвать нужный, а не наш.
        vm = compat.get("variant_mismatch")
        if isinstance(vm, dict) and vm:
            reasons.append("D4: для {} нужна версия {}, а это {}".format(
                vm.get("model"), "/".join(map(str, vm.get("theirs") or [])) or "другая",
                vm.get("ours") or "—"))
        # D5: серия заведена под несколько рынков (Epson WF-C5x90: EU T11C/D/E vs ASIA T11F/G).
        # Без региона в вопросе однозначный ответ неверен примерно в половине случаев.
        rn = compat.get("region_needed")
        if rn:
            reasons.append("D5: нужен регион — серия есть в версиях " + "/".join(map(str, rn)))
        # D6: у совместимости источник обязан быть детерминированным. «Модель» и «веб» — не источник,
        # они и есть D1; отдельной строкой это видно в очереди оператора.
        # «кэш» — повтор ОДОБРЕННОГО ответа, он законен; «кэш(веб)» — тот же веб, только вчерашний.
        ok_src = source.startswith(("карточка", "compat_ref:", "шаблон", "веб")) or (
            source.startswith("кэш") and "веб" not in source)
        if source and not ok_src:
            reasons.append(f"D6: источник «{source}» для совместимости не детерминирован")

    # D3 ОТКЛЮЧЁН 10.09.2026 (распоряжение Сергея). Правило требовало на ссылку из каталога
    # подтверждения справочником; справочник пуст, и правило держало обычную подстановку нашего
    # артикула и парного лота, работавшую до 08.09. Условие теперь ровно одно и проверяется НЕ
    # здесь, а на генерации: SKU существует в номенклатуре (catalog_by_code/catalog_offer ищут
    # по нашим листингам, _code_guard режет коды вне каталога). Код оставлен под флагом
    # FEEDBACK_D3=1 — включается без правки файла, если правило понадобится вернуть.
    if D3_ENABLED:
        ups = g.get("upsell") if isinstance(g.get("upsell"), dict) else None
        if ups and ups.get("unbacked"):
            reasons.append("допродажа без справочника: " + ", ".join(map(str, ups["unbacked"]))[:80])

    if kind == "question" and source == "модель":
        reasons.append("источник — только модель: ни карточка, ни каталог, ни веб не подтвердили")
    if kind == "question" and source.startswith("карточка-серия"):
        # «вариант серии, совпало по базе» строит _fam_status() двусторонним совпадением подстроки
        # (feedback_today.py:198): «412» матчится и в «B412dn», и в «MB472». Пока дефект A1 не
        # исправлен токенайзером (работа №8), это не доказательство, а догадка.
        reasons.append("совместимость выведена совпадением подстроки в названии серии (дефект A1)")
    if "каталог-после-веба" in source and D3_ENABLED:
        # Та же подстановка парного лота, что и D3: с 10.09.2026 она не держит публикацию.
        reasons.append("в ответ подставлен другой наш лот — проверьте, что текущий покупателю не подходит")

    # --- мягкие: то, что модель сообщила о себе. Только для ответов, которые она и писала ---
    if g.get("llm") and not eased:
        if kind == "question" and g.get("grounded") is False:
            reasons.append("модель сама не считает ответ обоснованным (grounded=false)")
        try:
            conf = float(row.get("draft_confidence") or 0)
        except (TypeError, ValueError):
            conf = 0.0
        if conf < MIN_CONF:
            reasons.append(f"уверенность {conf:.2f} ниже порога {MIN_CONF:.2f}")

    hard, trace = split_trace(reasons, kind)
    return (not hard), hard, trace


def reason_line(reasons, limit=300):
    """Одна строка причин для карточки оператора и лога отправки."""
    return "; ".join(reasons)[:limit]
