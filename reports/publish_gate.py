"""Машинный вердикт «можно ли публиковать черновик покупателю».

Работа №1 из аудита 25.08.2026 (`/opt/mp-knowledge/auto-inbox/rev-qa-audit-2026-08-25.md`).
До неё сигналы недоверия (`grounded`, `confidence`, `no_card`, `code_guard`, `qa_guard`) писались
в `raw_feedback.draft_grounding`, но их не читала НИ ОДНА развилка публикации: 94 % черновиков
с маркером неуверенности уходили покупателю по ✅ оператора, публиковались ответы с conf 0.0.

Два класса причин, и порядок между ними важен (замечание независимого ревью):

* ЖЁСТКИЕ — детерминированные, посчитаны кодом: маршрут `human`, маркер-заглушка `⚠️`, пустая
  карточка (`no_card`), сработавший `code_guard`/`qa_guard`, ответ без источника (`source='модель'`).
  Им верим: это факты конвейера.
* МЯГКИЕ — то, что о себе сообщила сама языковая модель (`grounded`, `confidence`). Им верим
  меньше, и строить на них вердикт в одиночку нельзя — но для запрета публикации их достаточно,
  запрет всегда в сторону «не отправлять».

Вердикт НЕ хранится в БД: он чистая функция от строки `raw_feedback` и пересчитывается на каждом
обращении. Отдельная колонка причины эскалации — работа №4, здесь не нужна.
"""
import json
import os
import re

from reports import request_class as rc

MIN_CONF = float(os.getenv("FEEDBACK_MIN_CONF", "0.6"))

# A1.2 (07.09.2026). Обещание от лица компании в МАШИННОМ черновике — запрет независимо от класса
# обращения: движок не знает ни условий возврата, ни остатка на замену. Реальные случаи — HP 953XL
# 03.09.2026 и Konica CMYK 31.08.2026, оба «оформим замену или возврат». К тексту, который написал
# оператор, стоп-лист НЕ применяется (см. verdict: судим только собственный черновик).
#
# Список из брифа (`возврат|замен|компенс|…`) прогнан по 344 черновикам за 30 дней и СУЖЕН: голое
# «замен»/«возврат» ловит техническую речь, к обязательствам не относящуюся — «замена чипа простая»,
# «надёжнее заменить на новый», «подскажем, как оформить возврат». Ловим то, что компания обещает
# СДЕЛАТЬ: глагол в первом лице мн. ч. либо конструкция обязательства («решим вопрос заменой»).
PROMISE_RX = re.compile(
    # «вернём» без хвоста: «вернёмся с ответом» — не обещание возврата (замечание ревью 08.09).
    r"верн[ёе]м(?!ся)|возместим|компенсируем|заменим|обменяем|дошл[её]м|дошлем|вышлем|оформим|"
    r"гарантируем|поможем\s+с\s+(?:возврат|замен|обмен)|"
    r"реш\w+\s+(?:вопрос|это|его|её|ее)?\s*[^.!?]{0,40}?(?:замен|возврат|обмен)|"
    r"за\s+наш\s+сч[ёе]т|бесплатн\w*\s+(?:замен|отправ|вышл|доставк|обмен)", re.I)

# A1.3. Утвердительный ответ о совместимости. «не подойдёт» — не утверждение, а отказ, его пропускаем.
# Голого «Да» в начале мало: движок пишет и «Да, к сожалению, не подойдёт» — поэтому зачин считается
# утверждением только при отсутствии отказа в тексте, а прямое «подойдёт» (FIT_RX уже с оглядкой
# на «не»/«нет») достаточно само по себе даже в смешанном ответе (замечание ревью 08.09.2026).
YES_RX = re.compile(r"^\s*(?:здравствуйте[!,.]?\s*)?(?:да\b|конечно\b)", re.I)
FIT_RX = re.compile(r"(?<!не )(?<!нет )\b(подойд[её]т|подойдут|подходит|подходят|совместим)", re.I)
NO_FIT_RX = re.compile(r"\bне\s+(?:подойд[её]т|подойдут|подходит|подходят|совместим\w*)|несовместим", re.I)


def _dead_text():
    """Текст хендоффа по «мёртвой» карточке. Импорт ленивый: card_rating тянет за собой БД, а гейт
    обязан оставаться чистой функцией и работать в тестах офлайн."""
    try:
        from reports.card_rating import DEAD_TEXT
        return DEAD_TEXT.strip()
    except Exception:
        return "\0"


def _customer_text(row):
    """Текст ПОКУПАТЕЛЯ (не черновика) — для класса обращения на строках, драфтнутых до 07.09.2026."""
    if row.get("kind") == "review":
        return " ".join(filter(None, [row.get("body"), row.get("pros"), row.get("cons")]))
    return row.get("body") or ""


def _same(a, b):
    """Тексты «те же» с точностью до регистра и пробелов — сравнение черновика с отправляемым."""
    return " ".join((a or "").split()).casefold() == " ".join((b or "").split()).casefold()


def _ground(row):
    g = row.get("draft_grounding")
    if isinstance(g, str):
        try:
            g = json.loads(g)
        except Exception:
            g = None
    return g if isinstance(g, dict) else {}


def verdict(row, text=None):
    """→ (allow: bool, reasons: list[str]). Пустой список причин = публиковать можно.

    text — фактический текст к отправке; если он отличается от черновика, значит его писал человек,
    и судить машинными сигналами о черновике уже нечего (вызывающий обязан пометить это override).
    """
    reasons = []
    kind = row.get("kind")
    g = _ground(row)
    body = (text if text is not None else row.get("draft_text")) or ""

    # --- жёсткие: детерминированные факты конвейера ---
    if row.get("draft_route") == "human":
        reasons.append("маршрут human (домен-фильтр или битый JSON модели)")
    if body.strip().startswith("⚠️"):
        reasons.append("маркер-заглушка «на человека», это не ответ покупателю")
    if g.get("no_card"):
        reasons.append("нет данных карточки — ответ собран по каталогу/вебу")
    if g.get("code_guard"):
        reasons.append("code-guard вырезал код расходника, которого нет ни в карточке, ни в вопросе")
    if g.get("qa_guard"):
        qa = g.get("qa_guard")
        det = ", ".join(map(str, qa))[:120] if isinstance(qa, (list, tuple)) else str(qa)[:120]
        reasons.append(f"qa-guard: {det}")
    # G (08.09.2026): подстановка из кэша утверждённых ответов, у которой карточка успела
    # измениться по полю из ключа (совместимость или атрибут). Текст был верен на момент
    # утверждения — публиковать его сейчас нельзя, оператор смотрит глазами.
    cache = g.get("cache") if isinstance(g.get("cache"), dict) else None
    if cache and cache.get("stale"):
        reasons.append("кэш устарел: карточка изменилась после утверждения ответа")

    # Текст оператора (text ≠ черновик) — не наш черновик: сравниваем без регистра и лишних
    # пробелов, иначе смена одной заглавной буквы объявляла машинный текст «правкой человека».
    own_draft = text is None or _same(text, row.get("draft_text"))

    # A1.1: претензия / дефект / недостача — только ручной ответ, чем бы черновик ни был обоснован.
    # Класс пишет _store() с 07.09.2026; на строках старше считаем его тут же по тексту покупателя.
    # Исключение одно — «мёртвая» карточка: там уходит сухой хендофф по правилу Сергея 24.08.2026,
    # и держать его = вечно копить в очереди отзывы по карточке, которую всё равно снимают.
    cls = g.get("request_class") or rc.classify(_customer_text(row), kind=kind, rating=row.get("rating"))
    # Исключение сужено (ревью 08.09.2026): template_id снимает запрет только с НЕТРОНУТОГО
    # черновика — отредактированный текст под тем же шаблоном судим на общих основаниях.
    dead = (g.get("template_id") == "dead_card" and own_draft) or body.strip() == _dead_text()
    if rc.is_claim(cls) and not dead:
        reasons.append("претензия, ручной ответ")

    # A1.2: обещание в СОБСТВЕННОМ черновике. Текст оператора не судим — он отвечает за свои
    # слова сам, и запрещать человеку слово «замена» движок не вправе.
    if own_draft:
        m = PROMISE_RX.search(body)
        if m:
            reasons.append(f"обещание в черновике: «{m.group(0)}»")

    # A1.3: «да, подойдёт» на модель, которой нет в списке совместимости карточки. Ровно этот путь
    # дал Epson C5890 (T945x), Canon LBP646 (075H) и HP 4303 (212A): совместимость взята из знания
    # модели или веба, карточка её не подтверждает. Порог уверенности такое не ловит — модель как
    # раз уверена. compat пишет feedback_today.py; на строках без него правило молчит.
    # Спросить могут несколько моделей: карточка подтверждает одну, вторая остаётся недоказанной,
    # а ответ утвердительный про обе. Поэтому смотрим НЕподтверждённые, а не «matched пуст».
    compat = g.get("compat") if isinstance(g.get("compat"), dict) else None
    if compat and compat.get("asked"):
        matched = compat.get("matched") or []
        unconfirmed = [a for a in compat["asked"] if a not in matched]
        affirm = FIT_RX.search(body) or (YES_RX.search(body) and not NO_FIT_RX.search(body))
        if unconfirmed and affirm:
            asked = ", ".join(map(str, unconfirmed))[:80]
            reasons.append(f"положительный ответ без подтверждения карточкой (модель {asked})")

    source = str(g.get("source") or "")
    if kind == "question" and source == "модель":
        reasons.append("источник — только модель: ни карточка, ни каталог, ни веб не подтвердили")
    if kind == "question" and source.startswith("карточка-серия"):
        # «вариант серии, совпало по базе» строит _fam_status() двусторонним совпадением подстроки
        # (feedback_today.py:198): «412» матчится и в «B412dn», и в «MB472». Пока дефект A1 не
        # исправлен токенайзером (работа №8), это не доказательство, а догадка.
        reasons.append("совместимость выведена совпадением подстроки в названии серии (дефект A1)")
    if "каталог-после-веба" in source:
        reasons.append("в ответ подставлен другой наш лот — проверьте, что текущий покупателю не подходит")

    # --- мягкие: то, что модель сообщила о себе. Только для ответов, которые она и писала ---
    if g.get("llm"):
        if kind == "question" and g.get("grounded") is False:
            reasons.append("модель сама не считает ответ обоснованным (grounded=false)")
        try:
            conf = float(row.get("draft_confidence") or 0)
        except (TypeError, ValueError):
            conf = 0.0
        if conf < MIN_CONF:
            reasons.append(f"уверенность {conf:.2f} ниже порога {MIN_CONF:.2f}")

    return (not reasons), reasons


def reason_line(reasons, limit=300):
    """Одна строка причин для карточки оператора и лога отправки."""
    return "; ".join(reasons)[:limit]
