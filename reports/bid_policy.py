"""ЕДИНАЯ политика ставок WB: пороги и вердикт по SKU — одно место на всех потребителей.

Потребители: страница «Ставки» (`web/marketing_app.py`, решение глазами) и ночная лестница
(`ops/wb_bid_ladder.py`, решение кроном). До 07.08.2026 каждая переписывала пороги у себя, и они
разъезжались при первой же правке одной из двух. Меняешь политику — меняешь ЗДЕСЬ.

Маржа берётся ЖИВАЯ (`mkt_margin_control`): текущая цена × закупка «почём купим сегодня»
(TheCartridge). Ретроспективная `margin_by_sku` гейтом быть не может — реклама крутит сегодняшние
цены, а помесячная маржа врёт на тонких месяцах.
"""

# ── Пороги решения ──────────────────────────────────────────────────────────────────────────────
WB_MARGIN_GATE = 25.0    # % маржи от НАШЕЙ цены (KPI Сергея, до СПП) — ниже не тянем в рекламе
WB_MARGIN_FLOOR = 15.0   # % — ЖЁСТКИЙ ПОЛ подъёма ставки (Сергей, 07.08.2026): между полом и гейтом
#                          ставку поднимаем и показываем в сводке; ниже пола — НЕ поднимаем вовсе,
#                          дороже реклама такую маржу просто съест
WB_DRR_CEIL = 10.0       # % ДРР — потолок-СТОП: рекомендация не заводит прогнозный ДРР выше него
WB_STEP_PCT = 10.0       # % шаг повышения ставки за раз (мягко: +10%, не прыжок к потолку)
WB_STEP_DAYS = 2         # дней между шагами — поднял, ждём реакции столько дней
WB_TEST_CAP = 20.0       # ₽ потолок ставки тест-фронта: не дала кликов к потолку → назад на пол


def raise_allowed(margin_own):
    """Можно ли поднимать ставку по этой марже. (можно, причина-отказа|None, ниже_KPI)

    Три зоны: маржа неизвестна → вслепую не поднимаем; ниже пола 15% → не поднимаем;
    между полом и гейтом 25% → поднимаем, но считаем и показываем в сводке.
    """
    if margin_own is None:
        return False, "маржа неизвестна", False
    if margin_own < WB_MARGIN_FLOOR:
        return False, f"маржа ниже пола {WB_MARGIN_FLOOR:.0f}%", True
    return True, None, margin_own < WB_MARGIN_GATE


def verdict(sold, mp, drr, spend, ad_orders, repriced=False, test_ready=False):
    """Вердикт по SKU. sold=продавался за 3 мес (qty>0); mp=маржа live%; drr=ДРР%;
    spend=расход рекламы; ad_orders=заказы, ПРИПИСАННЫЕ рекламе; repriced=цена выросла ≥25% над истор.;
    test_ready=кандидат тест-фронта (есть активная РК, рекламой не тестирован, ставка ниже потолка теста).
      ⚫ dead      — не продавался за квартал, но реклама жгла бюджет → балласт-снять
      ⚪ hold      — нет сигнала (нет расхода) или маржа неизвестна
      🔴 cut       — продавался, но маржа live ниже гейта 25% → снять с рекламы / поднять цену
      🧪 test      — маржа ок, продавался, 0 рекл-заказов, но рекламой НЕ тестирован и ставка на дне →
                     широкий тест +10%/день, пока не пойдут показы/заказы или не упрётся в потолок теста
      🟣 repriced  — маржа ок, продавался, реклама дала 0 заказов, НО цена выросла ≥25% над продажной
                     (продажи были на промо), и в тест-фронт не попал → бюджет-тест при текущей цене
      🔵 keep      — маржа ок, продавался ≈ по текущей цене, реклама дала 0 заказов → органика, держать
      🟡 expensive — маржа ок, реклама конвертит, но ДРР ≥ потолка → ставку вниз
      🟢 grow      — маржа ок, реклама конвертит, ДРР ниже потолка → есть куда поднимать ставку"""
    if not sold:
        return ("dead", "⚫ жжёт впустую") if (spend or 0) > 0 else ("hold", "⚪ нет сигнала")
    if mp is None:
        return ("hold", "⚪ маржа ?")
    if mp < WB_MARGIN_GATE:
        return ("cut", "🔴 снять / поднять цену")
    if (ad_orders or 0) == 0:
        if test_ready:
            return ("test", "🧪 тест-фронт")
        if repriced:
            return ("repriced", "🟣 цена выросла — тест")
        return ("keep", "🔵 держать на полу")
    if drr is not None and drr >= WB_DRR_CEIL:
        return ("expensive", "🟡 дорого — ставку вниз")
    return ("grow", "🟢 растить")
