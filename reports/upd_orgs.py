from datetime import date


# Ставка НДС берётся НЕ из уведомления ВБ: там она регулярно стоит неверная (22 %
# вместо 5 %), потому что ВБ не знает о переходе продавца на пониженную ставку.
# Истина — режим налогообложения продавца на дату уведомления:
#   Цифровой квадрат перешёл на НДС 5 % в 2025 году → все документы 2026 года с 5 %;
#   Дисквэр платит НДС на УСН с 01.08.2026 → до этой даты «без НДС», начиная с неё 5 %.
# Сумма выкупа (вкл. НДС) при этом неприкосновенна — это фактически уплаченные деньги;
# пересчитывается только разбивка «база / налог».
VAT_FROM = {
    "wb_acc1": [(date(2026, 1, 1), "5%")],
    "wb_acc2": [(date(2026, 8, 1), "5%"), (date(1, 1, 1), "без НДС")],
}


def vat_rate(account, doc_date, raw_rate):
    """Ставка НДС для позиции: по режиму продавца, а если период не описан — из уведомления."""
    for since, rate in VAT_FROM.get(account, []):
        if doc_date >= since:
            return rate
    return raw_rate


