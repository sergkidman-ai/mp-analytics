#!/bin/bash
# поток: mkt
# Ежедневный сбор рекламной статистики Ozon по ОБОИМ аккаунтам + самозалечивание дыр.
#
# ЕЖЕДНЕВНОГО ШАГА СТАВОК БОЛЬШЕ НЕТ (17.08.2026, по команде Сергея): вместо разгона
# «+10 % каждый день, пока есть запас по марже» действует НЕДЕЛЬНАЯ политика —
# tools/ozon_weekly_bids.py: раз в неделю смотрим прошлую неделю целиком и двигаем
# ставки на ±10 % по тирам (зелёный вверх, жёлтый держим, красный вниз, бордовый в пол).
# Разбор разгона 08–13.08 показал, почему: у поднятой когорты расход вырос
# 17 033 → 28 240 ₽ (+66 %), а заказы упали 100 → 81.
# Файл /etc/mp-ozon-ramp-frozen остаётся как страховка для старых копий скрипта.
#
# Ставки в кабинет из крона НЕ уходят — недельный план только считает списки.
set -u
# Корень берём от расположения самого скрипта: файл живёт и в общем чекауте,
# и в worktree, и запускаться должен из своего дерева, а не из чужого.
cd "$(dirname "$(readlink -f "$0")")/.." || exit 1
LOG=/opt/mp-analytics/logs/ozon_bid_ramp.log
mkdir -p /opt/mp-analytics/logs
YDAY="$(date -d yesterday +%F)"
{
  echo "=== $(date -Is) ==="
  for ACC in oz_acc1 oz_acc2; do
    echo "[$ACC]"
    # Отчёт Ozon асинхронный: NOT_STARTED = очередь на их стороне. Ждём долго —
    # именно нетерпение потеряло 13.08 и 16.08 (писали 0 строк и не возвращались).
    ./venv/bin/python tools/ozon_bid_ramp.py snapshot --account "$ACC" --date "$YDAY" --patience 1800
    # добираем всё, что не долилось за последние 10 дней
    ./venv/bin/python tools/ozon_bid_ramp.py gaps --account "$ACC" --days 10 --patience 1800
  done
} >> "$LOG" 2>&1
