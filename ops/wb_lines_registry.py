'''Реестр состава расходных строк Финансового отчёта ВБ (Баланс) — детализация «Отчётов МП · WB».

Ключ детализации у ВБ — не код услуги (как у Ozon), а ТЕКСТ из сырья: `supplier_oper_name`
для логистики и баллов, `bonus_type_name` для штрафов / прочих удержаний / компенсаций.
Текст несёт номер и дату документа («Оказание услуг «WB Продвижение» документ №123 от 01.07.2026»),
поэтому перед группировкой прогоняется через norm() — иначе каждый недельный документ дал бы
свою подстроку, и вместо пяти строк детализации получилось бы двести.

Логистика текстового разреза не имеет: там ключ синтетический (`L:fwd` / `L:rev` / `L:corr`),
признак — поля delivery_amount / return_amount строки «Логистика» и отдельная операция
«Коррекция логистики».

CODES нужен двум вещам: (1) короткая подпись в отчёте вместо казённой формулировки ВБ;
(2) аудит — ключ ВНЕ реестра значит, что ВБ завёл новый тип удержания, и он молча уедет
в «Прочие удержания». Правило: сначала свериться с составом блока в ЛК, потом добавлять сюда.
Неизвестный ключ не теряется — печатается как есть (label() возвращает сам ключ).
'''
import re

_TAIL = re.compile(r"\s*(документ|док\.|№)\s*.*$", re.I)
_SP = re.compile(r"\s+")
_MONTH = (r"январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр")

# Схлопывание «одна операция = своя формулировка»: ВБ вшивает в текст идентификатор отзыва или
# месяц отчёта, и без этих правил 994 списания за отзывы дали бы 994 подстроки вместо одной.
COLLAPSE = (
    (re.compile(r"^Списание за отзыв\b.*", re.I), "Списание за отзыв (акция)"),
    (re.compile(r"\s*за\s+(?:" + _MONTH + r")\w*\s+\d{4}$", re.I), ""),
)


def norm(s):
    """Ключ детализации: без номера/даты документа и идентификатора отзыва, схлопнутые пробелы."""
    s = _TAIL.sub("", (s or "").strip()).strip(" .,-—")   # хвост режем ДО схлопывания: «… за апрель
    #  2026, документ №…» → без запятой правило месяца ловится якорем конца строки
    for rx, rep in COLLAPSE:
        s = rx.sub(rep, s)
    return _SP.sub(" ", s).strip(" .,-—")


CODES = {
    # ---- Логистика (синтетический разрез по признакам строки) ----
    "L:fwd":  ("delivery", "Прямая — доставка покупателю"),
    "L:rev":  ("delivery", "Обратная — возвраты и невыкупы"),
    "L:corr": ("delivery", "Коррекция логистики"),
    # ---- Баллы и лояльность (ключ = supplier_oper_name с префиксом OP:) ----
    "OP:Сумма удержанная за начисленные баллы программы лояльности":
        ("points", "Баллы программы лояльности"),
    "OP:Сумма баллов, удержанных за покупку товаров":
        ("points", "Баллы за покупку товаров"),
    "OP:Коррекция суммы удержанной за начисленные баллы программы лояльности":
        ("points", "Коррекция баллов лояльности"),
    # ---- Штрафы (ключ = bonus_type_name) ----
    "Штраф МП. Невыполненный заказ (отмена продавцом)": ("penalty", "Отмена заказа продавцом"),
    "Штраф МП. Невыполненный заказ": ("penalty", "Невыполненный заказ"),
    "Сторно. Штраф МП. Невыполненный заказ": ("penalty", "Сторно штрафа за невыполненный заказ"),
    "Штраф МП. Невыполненный заказ (отправка товара отличного от заявленного)":
        ("penalty", "Отправлен не тот товар"),
    "Подмена товара (с фото)": ("penalty", "Подмена товара (с фото)"),
    "Платное хранение возвратов на ПВЗ более 3 дней": ("penalty", "Хранение возвратов на ПВЗ >3 дней"),
    # ---- Прочие удержания ----
    "Списание за отзыв (акция)": ("other", "Списания за отзывы (акция «Отзывы»)"),
    "Отчет об утилизированном товаре (по складу)": ("other", "Утилизация товара"),
    # ---- Компенсации ВБ нам (deduction<0) ----
    "Добровольная выплата за товары, пострадавшие в результате обстоятельств непреодолимой силы":
        ("compensation", "Выплата за товар, утраченный на складе (форс-мажор)"),
}


def label(code):
    """Подпись подстроки: из реестра, иначе сам ключ (новый тип виден, но не теряется)."""
    e = CODES.get(code)
    return e[1] if e else code


def line_of(code):
    """Строка отчёта по ключу — только для аудита (в расчёте строку задаёт SQL-разрез)."""
    e = CODES.get(code)
    return e[0] if e else None
