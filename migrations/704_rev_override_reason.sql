-- Очередь модерации 10.09.2026: кнопка «✅ Отправить как есть» возвращается на заблокированную
-- карточку. Нажатие = оператор осознанно публикует вопреки машинному вердикту, и этот факт обязан
-- остаться в данных: без него нельзя ни измерить долю ложных блоков, ни разобрать инцидент
-- «кто это отправил». Пишем ПРИЧИНУ блока, которую обошли, и кто обошёл.
ALTER TABLE raw_feedback ADD COLUMN IF NOT EXISTS override_reason text;

COMMENT ON COLUMN raw_feedback.override_reason IS
    'Причина блока publish_gate, которую оператор обошёл кнопкой «Отправить как есть», и кто обошёл';
