-- Что было не так: у 21 905 карточек из 22 413 своих продаж за месяц нет, и им ставилась
-- медиана аккаунта — плоские 134 ₽ логистики и 188 ₽ «прочего» независимо от габаритов,
-- цены и категории. Медиана каталога описывает средний короб (8+ литров, лазерные и наборы),
-- а не струйный картридж на 0.5 л, которому Ozon выставляет 77 ₽. «Прочее» же вообще не
-- рубли, а проценты от цены (Premium Pro + Звёздные + эквайринг + реклама): 424 ₽ на чеке
-- 5 100 ₽ и 26 ₽ на карточке за 400 ₽ — одна медиана на обе не годится.
--
