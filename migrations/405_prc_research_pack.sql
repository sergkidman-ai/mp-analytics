-- Вес и размеры упаковки в разведке (уточнение Сергея 09.08).
--
-- Спрашивая сеть, человек всегда спрашивал ОДНИМ запросом на строку прайса и сразу обо всём:
-- нероссийские модели убрать, для остальных — принтеры в РФ, доза полной заправки, ресурс,
-- ВЕС товара в упаковке и РАЗМЕРЫ упаковки. Двух последних в таблице не было, а без них
-- карточку не заведёшь: вес и короб нужны для логистики маркетплейса.
--
-- Это ВЕБ-размер, а не короб поставщика. По правилу приоритета источников (CLAUDE.md, габариты,
-- п. 12) короб чистого поставщика из `supplier_dims` всегда старше веба; веб берём только там,
-- где поставщицкого нет — то есть ровно в случае новинки. Поэтому источник помечаем
-- (`pack_source`) и не выдаём его за замер.
ALTER TABLE prc_model_research
    ADD COLUMN IF NOT EXISTS weight_kg   numeric(10,3),   -- вес товара в упаковке, кг
    ADD COLUMN IF NOT EXISTS pack_l_cm   numeric(10,1),   -- упаковка: длина, см
    ADD COLUMN IF NOT EXISTS pack_w_cm   numeric(10,1),   -- ширина, см
    ADD COLUMN IF NOT EXISTS pack_h_cm   numeric(10,1),   -- высота, см
    ADD COLUMN IF NOT EXISTS pack_source text,            -- откуда вес/короб: «веб» + чей сайт
    ADD COLUMN IF NOT EXISTS asked_row   text;            -- строка прайса, которой спрашивали

COMMENT ON COLUMN prc_model_research.pack_source IS
    'Источник веса и короба: это ВЕБ-данные (упаковка производителя), не короб поставщика. '
    'Короб из supplier_dims всегда приоритетнее — см. CLAUDE.md, габариты, правило 12.';
