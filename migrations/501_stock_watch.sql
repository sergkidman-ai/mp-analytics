-- поток: ev
-- Подписка на остаток товара ПОСТАВЩИКА: «скажи, когда закончится».
--
-- Почему подписка, а не список кодов в коде. Просьба пришла на 4 кода (HP 913A CMYK у ОДИССЕЯ),
-- и следить за ВСЕМИ остатками не надо — это огромный поток данных без адресата. Но такие
-- просьбы будут повторяться, и каждый раз править исходник и катить деплой — неправильно:
-- добавить код должно быть строкой в таблице (командой в боте), а не задачей разработчику.
--
-- Ключ — ms_product.code («Код» в МойСкладе, например 3804at). Это товар КОНКРЕТНОГО
-- поставщика, и остаток у него один. Джойнить по external_code (наша карточка 3804) нельзя:
-- под ней 9–11 строк разных поставщиков, и «закончился» стало бы значить совсем другое —
-- «товар негде взять вообще», а не «у нашего поставщика кончился».

CREATE TABLE IF NOT EXISTS stock_watch (
    id          bigserial   PRIMARY KEY,

    ms_code     text        NOT NULL,                          -- ms_product.code, напр. '3804at'
    store       text        NOT NULL DEFAULT 'Удаленный склад', -- склад из supplier_stock

    -- Порог предупреждения в штуках. Ноль — это уже поздно (карточка встала, продажи потеряны),
    -- поэтому предупреждаем заранее. Считать «на сколько дней хватит» здесь нельзя: sold_30d
    -- у строк поставщика пустой. Порог свой на каждый код — расход у них разный.
    threshold   numeric     NOT NULL DEFAULT 5,

    chat_id     bigint,                                        -- кому слать; NULL → TG_PRC_NOTIFY_ID
    active      boolean     NOT NULL DEFAULT true,
    note        text,

    -- Антидребезг. Остаток колеблется у порога, и без памяти состояния сторож слал бы
    -- уведомление каждый прогон. Пишем ПОСЛЕДНЕЕ сообщённое состояние и повторяем сообщение
    -- только при СМЕНЕ состояния: ok → low → zero и обратно (восстановление тоже новость).
    last_state  text        NOT NULL DEFAULT 'ok'
                            CHECK (last_state IN ('ok', 'low', 'zero', 'nodata')),
    last_stock  numeric,
    notified_at timestamptz,

    created_at  timestamptz NOT NULL DEFAULT now(),

    UNIQUE (ms_code, store)
);

CREATE INDEX IF NOT EXISTS stock_watch_active_idx ON stock_watch (active) WHERE active;
