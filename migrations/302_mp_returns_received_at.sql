-- поток: ret — когда возврат физически оказался у нас (10.08.2026).
-- Площадки такой даты не дают: у Ozon `arrived_moment` — приезд коробки в ПВЗ, у ВБ
-- `readyToReturnDt` — готовность к выдаче, у Яндекса и Real-FBS нет ничего. Отсюда своя
-- отметка: `collect` ставит её в момент, когда впервые видит статус «получено».
-- Перезаписывать нельзя — иначе дата поедет при каждом сборе.
ALTER TABLE mp_returns ADD COLUMN IF NOT EXISTS received_at timestamptz;

-- Строки, уже полученные до появления колонки, отмечаем лучшим, что есть у площадки.
-- Без этого первый же сбор проштампует их сегодняшним числом и недельный отчёт покажет
-- полугодовую историю как «получено вчера».
UPDATE mp_returns
   SET received_at = COALESCE(arrived_at, created_at, first_seen)
 WHERE received_at IS NULL
   AND status_name IN ('Получен', 'Выдано', 'забран', 'Получена');

COMMENT ON COLUMN mp_returns.received_at IS
  'Когда возврат стал «получен» по нашим наблюдениям; до 10.08.2026 — дата площадки';
