-- поток: mkt
-- 118_query_econ_bid_ceiling.sql — потолок ставки за клик в витрине фраз.
--
-- Зачем: список «поднять_ставку» без потолка опасен — дешёвый SKU может просить ставку,
-- которая съест всю его маржу. Потолок считается из юнит-экономики самого товара:
--
--   потолок CPC = (маржа с заказа − процент «оплаты за заказ» с заказа) × конверсия клика
--
-- Конверсия берётся не с потолка, а из факта: по кампаниям `ozon_ads` за последний месяц,
-- сгруппированным в ценовые бакеты по их же среднему чеку (ad_revenue / orders).
-- Процент — ставка «оплаты за заказ» аккаунта: она ЕДИНА на весь ассортимент (5/7/9 %),
-- по SKU не выбирается, поэтому в расчёт входит как константа аккаунта.
ALTER TABLE mkt_ozon_query_econ ADD COLUMN IF NOT EXISTS cr_bucket   numeric;  -- конверсия клика, доля
ALTER TABLE mkt_ozon_query_econ ADD COLUMN IF NOT EXISTS bid_ceiling numeric;  -- потолок CPC, ₽
