-- поток: ev
-- Дневник управленческих событий — общий слой «почему» под всеми отчётами Пульта.
--
-- Зачем таблица, а не заметки в файле. Отчёт показывает ЧТО произошло, но не ПОЧЕМУ: провал
-- на Дисквэре 21.08 читается как просадка, хотя 20.08 мы сами отключили «Звёздные товары»;
-- рост ДРР — как «реклама подорожала», хотя площадка подняла комиссию. Событие должно лежать
-- рядом с цифрой и подниматься вместе с ней — значит в БД, а не в переписке.
--
-- Три источника событий, одна таблица (различаются полем kind):
--   own    — наше решение (отключили программу, запустили бандлы, сменили срок выплат);
--   mp     — решение площадки (тарифы, комиссии, авто-подключённые услуги, пожар на складе);
--   supply — состояние поставщика (кончился товар по коду).
-- Складывать их врозь смысла нет: читателю нужна ОДНА лента, наложенная на график.

CREATE TABLE IF NOT EXISTS biz_events (
    id          bigserial   PRIMARY KEY,

    -- Дата события. date_to заполняем только у периодов (акция шла две недели); для точечного
    -- события NULL, а не копия event_date — иначе не отличить «день» от «период в один день».
    event_date  date        NOT NULL,
    date_to     date,

    kind        text        NOT NULL CHECK (kind IN ('own', 'mp', 'supply')),

    -- Границы влияния. NULL = «весь бизнес»: событие вроде смены срока выплат не привязано
    -- к площадке-аккаунту, и подставлять туда что-то ради непустого поля — врать.
    platform    text,                       -- wb | ozon | yandex | NULL
    account     text,                       -- oz_acc1 | oz_acc2 | wb_acc1 | wb_acc2 | NULL

    -- Что затронуто. scope_ref читается по scope_kind: sku_list → коды через запятую,
    -- warehouse → имя склада, category → предмет. all → scope_ref пустой.
    scope_kind  text        NOT NULL DEFAULT 'all'
                            CHECK (scope_kind IN ('all', 'sku_list', 'category', 'warehouse')),
    scope_ref   text,

    title       text        NOT NULL,
    details     text,

    -- Гипотеза и срок проверки. Смысл дневника не в архиве, а в возврате к событию: «ждали
    -- роста выкупа — посмотри через две недели». Без review_at событие тихо забывается.
    expect      text,
    review_at   date,

    author      text,
    -- tg — надиктовано в бот; web — форма дашборда; auto_mail / auto_news / auto_stock — сторожа.
    source      text        NOT NULL DEFAULT 'web',

    -- Ключ идемпотентности для АВТОМАТИЧЕСКИХ событий: письмо площадки и срабатывание сторожа
    -- приходят повторно, и без него дневник забьётся дублями. У ручных событий NULL — человек
    -- вправе завести два похожих события одним днём.
    dedup_key   text        UNIQUE,

    created_at  timestamptz NOT NULL DEFAULT now()
);

-- Главный запрос дневника — «что было в этом окне»: лента на главной и 📌-маркеры на графике.
CREATE INDEX IF NOT EXISTS biz_events_date_idx  ON biz_events (event_date DESC);
-- Второй по частоте — «чем закончилось»: события, у которых подошёл срок проверки эффекта.
CREATE INDEX IF NOT EXISTS biz_events_review_idx ON biz_events (review_at) WHERE review_at IS NOT NULL;
