-- 064: wb_stocks.captured_ts — момент снятия снимка остатков (не только дата).
-- Зачем: captured_at это DATE, и вкладка «Распродажа остатков ВБ» могла показать лишь день
-- последнего обновления. Когда прогон падает (OOM 04.08.2026) или встаёт токен юрлица, важно
-- видеть ЧАС снимка, иначе «обновлено сегодня» скрывает снимок 12-часовой давности.
-- Историю не переписываем: у старых строк остаётся NULL (реального времени мы не знаем),
-- страница для них честно показывает одну дату. DEFAULT now() заполняет только новые снимки.
ALTER TABLE wb_stocks ADD COLUMN IF NOT EXISTS captured_ts timestamptz;
ALTER TABLE wb_stocks ALTER COLUMN captured_ts SET DEFAULT now();
