-- поток: inv
-- 213: разнесение платежа НАЗАД — статьи, которые оплачивают уже прошедшие периоды.
--
-- Задача Сергея 04.08.2026: «для статьи Налоги и взносы период оплаты не вперёд на несколько
-- месяцев, а назад — налоги платятся за прошлые периоды». Механика разнесения уже есть
-- (миграция 209: доли считаются от `bank_txn_opex.start_month` вперёд), не хватало только
-- признака направления у статьи.
--
-- Семантика: N месяцев, ЗАКАНЧИВАЯ месяцем ПЕРЕД платежом.
--   вперёд (как было): платёж 08.2026, N=3 → август, сентябрь, октябрь;
--   назад  (spread_back): платёж 08.2026, N=1 → июль; N=3 → май, июнь, июль.
-- То есть start_month = месяц_платежа − N. Взносы за июль, уплаченные в августе, ложатся
-- в расходы июля; НДС, уплаченный в июле за II квартал, — при N=3 в апрель–июнь.
--
-- Флаг живёт у СТАТЬИ, а не у платежа: направление — свойство вида расхода, а не отдельной
-- операции. Вью 209 не трогаем: она считает от start_month, направление уже вшито в него.

ALTER TABLE opex_category ADD COLUMN IF NOT EXISTS spread_back BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN opex_category.spread_back IS
    'true = платёж закрывает ПРОШЛЫЕ месяцы: разнесение идёт назад, start_month = месяц платежа − N '
    '(налоги и взносы); false = вперёд от месяца платежа (аренда, подписки, лицензии)';

-- Статья из задачи. Остальные налоговые статьи (например «Налоги ФОТ») Сергей включает сам
-- галкой на экране «Выписки» — за него не решаем.
UPDATE opex_category SET spread_back = true WHERE name = 'Налоги и взносы';

-- Уже размеченные платежи таких статей пересобираем под новое направление, иначе флаг
-- работал бы только для будущих разметок, а прошлые месяцы остались бы кривыми.
UPDATE bank_txn_opex a
   SET start_month = (date_trunc('month', t.operation_date)
                      - (a.spread_months || ' month')::interval)::date,
       updated_at  = now()
  FROM bank_txn t, opex_category c
 WHERE t.id = a.txn_id AND c.id = a.category_id AND c.spread_back
   AND a.start_month <> (date_trunc('month', t.operation_date)
                         - (a.spread_months || ' month')::interval)::date;
