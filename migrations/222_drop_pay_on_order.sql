-- 222 (inv): откат флага pay_on_order (миграция 220).
--
-- Флаг заводился под «отсрочка от даты заказа, а не от приёмки», но разбор показал, что срок
-- оплаты НИКОГДА не считался от приёмки: `due_date = order_date + deferral_days` и до 220.
-- Приёмка была и остаётся гейтом СУММЫ, а не даты: платим за то, что доехало.
--
-- Решение Сергея 04.09: срок считаем от заказа (как и считали), но на момент отправки платежа
-- приёмку проверяем всегда — «если за 6 дней товар до нас не доехал, оплачивать нечего».
-- Значит выключатель гейта не нужен ни одному поставщику, а включённым он разрешал бы платить
-- за неполученный товар. Убираем, чтобы этой возможности не было вовсе.
--
-- Заказы, выпущенные из-под гейта, обратно НЕ правим руками: ближайший прогон поллера сам
-- вернёт непринятые в 'waiting_receipt' веткой `held` (сверка с shippedSum в МС надёжнее
-- любого массового UPDATE вслепую).
--
-- Срок отсрочки Блоссома (6 дней, миграция 221) не трогаем.
ALTER TABLE supplier_payment_terms DROP COLUMN IF EXISTS pay_on_order;
