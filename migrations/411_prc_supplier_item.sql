-- поток: prc
-- Кэш наименований товара поставщика по его артикулу.
-- Нужен там, где прайс к нам не приходит (Булат, ВТТ, Рамис, Блоссом): внешний загрузчик
-- присылает письмом только то, что не сопоставил, и в этом файле от товара есть ОДИН артикул —
-- ни наименования, ни модели, ни ресурса. Без наименования шесть признаков не посчитать,
-- поэтому имя добираем с сайта поставщика и держим здесь: письма приходят несколько раз в день,
-- а состав артикулов почти не меняется — без кэша каждый разбор дёргал бы сайт заново.
CREATE TABLE IF NOT EXISTS prc_supplier_item (
  supplier_key text        NOT NULL,
  article      text        NOT NULL,
  name         text        NOT NULL,
  source       text        NOT NULL,        -- откуда взято имя, напр. 'bulat-group.ru'
  fetched_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (supplier_key, article)
);
