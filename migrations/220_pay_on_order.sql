-- 220 (inv): отсрочка может считаться ОТ ДАТЫ ЗАКАЗА, а не от приёмки.
--
-- До этого гейт приёмки был зашит в код: по отсрочке платим только за принятый товар
-- (решение 30.07). Но у части поставщиков договор считает отсрочку от даты заказа/счёта,
-- и товар едет уже после оплаты — там гейт держит заказ в 'waiting_receipt' бесконечно.
-- Флаг делает базу отсрочки свойством ДОГОВОРА, а не константой кода.
--
-- false (по умолчанию) — как было: в пачку идёт только принятое (min(sum, shippedSum) − payedSum);
-- true  — в пачку идёт весь недоплаченный заказ, приёмку не ждём.
-- Срок оплаты в обоих случаях один и тот же: order_date + deferral_days.
ALTER TABLE supplier_payment_terms
    ADD COLUMN IF NOT EXISTS pay_on_order boolean NOT NULL DEFAULT false;

-- Блоссом (ООО «Картридж Трейд»): 3 дня от даты заказа у обеих наших фирм.
-- У Дисквэра стояло 4 дня — лишний день был поправкой на доставку, при отсчёте от заказа
-- он не нужен.
UPDATE supplier_payment_terms
   SET pay_on_order = true, deferral_days = 3, updated_at = now()
 WHERE inn = '9718075418';
