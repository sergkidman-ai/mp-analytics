-- Взаимозачёт баллов Маркета против его же услуг: сохраняем начисленное и зачтённое.
--
-- Экономика (разбор docs/reports/ya_subsidy_2026-08-19.md и mp_discounts_unified_2026-08-19.md):
-- Маркет продаёт по НАШЕЙ цене, часть скидки покупателю платит сам (субсидия/баллы) и возвращает
-- себе эту сумму, начисляя услуги по раздутому тарифу и тут же гася их зачётом. Деньгами с нас
-- списывается только остаток. До сих пор в raw_yandex_services лежала лишь эта денежная часть
-- (cost = TOTAL_AMOUNT / «Стоимость услуги»), поэтому вкладка Маркета — единственная из трёх,
-- где оборот показан НЕТТО (деньги покупателя), а удержания — уже после зачёта.
--
--   accrued — начислено до скидок и зачёта (API: AMOUNT_WITHOUT_BONUSES;
--             файл ЛК: «Стоимость услуги без скидок и наценок»). NULL там, где колонки нет.
--   netting — зачтено баллами Маркета (API: NETTING; файл ЛК: «Скидка за участие
--             в совместных акциях»). 0 = зачёта не было, NULL = источник колонку не отдаёт.
--
-- Контроль (июль-2026, ya_acc1): placement начислено 1 153 901, зачтено 786 102, деньгами
-- 359 601; зачёт по всем услугам 935 413 ≈ субсидия по заказам 962 257 (−2,8 %, лаг акта).
ALTER TABLE raw_yandex_services
    ADD COLUMN IF NOT EXISTS accrued numeric(14,2),
    ADD COLUMN IF NOT EXISTS netting numeric(14,2);

COMMENT ON COLUMN raw_yandex_services.accrued IS 'начислено до скидок и зачёта, ₽ (NULL — нет в источнике)';
COMMENT ON COLUMN raw_yandex_services.netting IS 'погашено баллами Маркета, ₽ (NULL — нет в источнике)';
