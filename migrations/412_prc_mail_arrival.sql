-- поток: prc — история ПРИХОДА писем с прайсами: по ней сторож учит расписание поставщика.
--
-- Почему не хватает журнала `prc_price_load`: он знает только про НАШИ удачные прогоны.
-- Письмо, чью загрузку отменила проверка аномалий, до журнала не доходит; письмо, пришедшее
-- пока сторож стоял, там тоже не появится. А расписание поставщика надо считать по факту
-- ОТПРАВКИ, иначе наши простои читаются как «поставщик замолчал».
--
-- День хранится один раз: у Булата и Солюшнс принта письмо приходит несколько раз в сутки,
-- а для расписания важно только первое — по нему считается срок ожидания.
CREATE TABLE IF NOT EXISTS prc_mail_arrival (
  supplier_key text        NOT NULL,
  letter_date  date        NOT NULL,     -- дата письма по Москве
  first_at     timestamptz NOT NULL,     -- первое письмо этого дня
  subject      text,
  filename     text,
  PRIMARY KEY (supplier_key, letter_date)
);
