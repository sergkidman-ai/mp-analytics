-- Подписка сторожа остатков получает ПОСТАВЩИКА, а джойн — агрегат.
--
-- Повод (23.08.2026, задача Натальи по складу «Звездный»): у кода поставщика в ms_product
-- может быть НЕ одна карточка, а две — у 5439sp–5442sp это `ООО "Солюшнс принт" МСК`
-- (новая, лежит на «Звездном») и `ООО "Солюшнс принт"` (старая, только на «Озоне»).
-- Джойн `p.code = w.ms_code` без агрегации давал на одну подписку ДВЕ строки: одну с
-- остатком, другую с NULL — сторож видел бы `nodata` и слал ложное «нет данных».
--
-- Лечим двумя движениями: остаток по подписке считаем СУММОЙ по всем ms_id этого кода
-- на складе (см. read_current в ops/stock_watch.py), а если следить нужно за товаром
-- КОНКРЕТНОГО поставщика — записываем его в подписку и фильтруем.
-- NULL в supplier = «любой поставщик под этим кодом».

ALTER TABLE stock_watch ADD COLUMN IF NOT EXISTS supplier text;

-- Ключ подписки был (код, склад) — теперь у одного кода на одном складе может быть
-- две подписки на разных поставщиков. NULL в UNIQUE считается уникальным сам по себе,
-- поэтому ключ — по выражению, иначе «поставщик не указан» продублируется молча.
ALTER TABLE stock_watch DROP CONSTRAINT IF EXISTS stock_watch_ms_code_store_key;
CREATE UNIQUE INDEX IF NOT EXISTS stock_watch_key_idx
    ON stock_watch (ms_code, store, coalesce(supplier, ''));
