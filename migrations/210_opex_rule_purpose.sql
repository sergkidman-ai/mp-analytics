-- поток: inv
-- 210: фрагмент назначения в правиле разметки опер. расходов.
--
-- Зачем. Ключ «только ИНН контрагента» оказался слишком широким там, где банк подставляет
-- себя контрагентом: у Дисквэра все карточные покупки и собственные комиссии идут от
-- ПАО Сбербанк (ИНН 7707083893), и одно правило «Сбербанк → Упаковка» накрыло 38 разнородных
-- платежей. Теперь у правила есть НЕОБЯЗАТЕЛЬНЫЙ фрагмент назначения: пусто — правило по
-- контрагенту, как раньше; заполнено — правило срабатывает только на платежах, в назначении
-- которых этот фрагмент встречается (без учёта регистра).
--
-- Приоритет при совпадении нескольких правил — самое специфичное (длинный фрагмент), см.
-- collectors/bank_txn_store.apply_rules.

ALTER TABLE opex_rule ADD COLUMN IF NOT EXISTS purpose_like TEXT;

COMMENT ON COLUMN opex_rule.purpose_like IS
    'Необязательный фрагмент назначения платежа: пусто = правило на всего контрагента, '
    'заполнено = только на платежи, где фрагмент встречается в назначении (регистр не важен)';

-- Уникальность теперь по паре «контрагент + фрагмент»: у одного ИНН может быть общее правило
-- и несколько уточнённых (карточные покупки в разных ТУ).
DROP INDEX IF EXISTS uq_opex_rule_inn;
DROP INDEX IF EXISTS uq_opex_rule_name;
CREATE UNIQUE INDEX IF NOT EXISTS uq_opex_rule_inn
    ON opex_rule (cp_inn, (coalesce(lower(purpose_like), '')))
    WHERE coalesce(cp_inn, '') <> '';
CREATE UNIQUE INDEX IF NOT EXISTS uq_opex_rule_name
    ON opex_rule (cp_name_key, (coalesce(lower(purpose_like), '')))
    WHERE coalesce(cp_name_key, '') <> '';
