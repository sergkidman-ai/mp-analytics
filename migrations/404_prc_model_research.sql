-- поток: prc
-- Разведка модели картриджа в сети: ответы на вопросы, которых нет ни в прайсе, ни у нас в базе.
--
-- Четыре вопроса, на которые до сих пор отвечали гаданием (разбор тонера Kyocera TKY4, 09.08):
-- модель ходит на российском рынке или нет; популярна ли настолько, чтобы заводить карточку;
-- сколько тонера/чернил нужно на ПОЛНУЮ заправку именно этой модели; и полный список принтеров
-- — у поставщика его в строке прайса нет вовсе, а наши собственные названия неполные (у TK-330
-- в базе стоял один FS-4000DN).
--
-- Ключ — МОДЕЛЬ, а не строка прайса: одна и та же TK-3190 приходит в разных прайсах и разных
-- загрузках, и платить за неё второй раз незачем. Запрос платный (серверный web_search),
-- поэтому таблица одновременно и кэш, и журнал расхода: смета считается ДО (арифметикой),
-- факт (`searches`, `cost_usd`) пишется ПОСЛЕ из `usage.server_tool_use.web_search_requests`.
--
-- Спрашивать могут и про принтер: в хвосте «…для принтера Kyocera P6030CDN» поставщик пишет
-- то принтеры, то модели картриджей, и различить их по формулировке нельзя. Тогда сеть сама
-- называет штатный картридж (`cartridge`) и отвечает уже по нему — вопрос «сколько тонера
-- на полную заправку» от этого не меняется.
--
-- Доза и принтеры без ссылки-источника не принимаются — пишется NULL / пустой список.
-- Правило то же, что в габаритах: синтетическая цифра дороже отсутствующей.

-- Два поля под модель, потому что пишут её по-разному. `model` — как написано в прайсе
-- («TK-3190», «CF210A»), это то, что видит человек. `model_key` — ключ кэша без дефисов и
-- регистра («TK3190»): «TK-3190» у Кактуса и «TK3190» у другого поставщика — одна и та же
-- модель, и платить за неё дважды незачем.
CREATE TABLE IF NOT EXISTS prc_model_research (
    model           text PRIMARY KEY,          -- как пишут в прайсе: «TK-3190»
    model_key       text NOT NULL UNIQUE,      -- ключ кэша: «TK3190»
    cartridge       text,                      -- штатный картридж, если спросили про принтер
    ru              boolean,                   -- ходит ли на российском рынке
    popularity      text,                      -- high | mid | low | none
    resource_pages  integer,                   -- ресурс картриджа, страниц
    refill_amount   numeric(10,2),             -- доза полной заправки
    refill_unit     text,                      -- «г» | «мл»
    printers        jsonb NOT NULL DEFAULT '[]'::jsonb,   -- полный перечень принтеров
    verdict         text,                      -- краткий вывод: заводить / не заводить
    why             text,                      -- на чём основан вывод
    confidence      text,                      -- high | mid | low
    sources         jsonb NOT NULL DEFAULT '[]'::jsonb,   -- [{url, title}]
    llm_model       text,                      -- какой моделью спрашивали
    searches        integer,                   -- фактическое число веб-поисков
    cost_usd        numeric(10,4),             -- фактическая оценка расхода
    asked_at        timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE prc_model_research IS
    'Кэш платной веб-разведки по модели картриджа (поток prc): рынок РФ, популярность, '
    'доза полной заправки, полный список принтеров. Ключ — модель, запрос только с подтверждением сметы.';
