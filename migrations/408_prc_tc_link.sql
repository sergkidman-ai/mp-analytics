-- поток: prc
-- Связи универсальных моделей каталога TheCartridge (задача Сергея 14.08.2026).
--
-- Универсальный картридж закрывает не одну нашу позицию: 0002 (Q2612A/12A) — это же товар,
-- что 5335 (FX-10), 5336 (703) и 5334. До сих пор такое знание жило ТОЛЬКО в МойСкладе,
-- доп. полем «Связь», проставленным руками, и заполнено было не у всех карточек одного
-- внешнего кода. По просьбе с нашей стороны программист ТК добавил связи в выгрузку моделей
-- (`incoming_references` / `outgoing_references`) — теперь это факт первоисточника, а не
-- ручная пометка на карточке поставщика.
--
-- Направление храним как отдали: на первой странице (200 моделей) списки разошлись у 76 —
-- то есть incoming и outgoing НЕ одно и то же, схлопывать их в «связан» нельзя, иначе мы
-- припишем источнику то, чего он не говорил. Для вопроса «это один и тот же товар?» берётся
-- объединение, для разбора «кто на кого ссылается» — колонки по отдельности.

CREATE TABLE IF NOT EXISTS prc_tc_link (
    external_code text NOT NULL REFERENCES prc_tc_model(external_code) ON DELETE CASCADE,
    ref_code      text NOT NULL,                 -- внешний код связанной модели
    outgoing      boolean NOT NULL DEFAULT false,
    incoming      boolean NOT NULL DEFAULT false,
    PRIMARY KEY (external_code, ref_code)
);
CREATE INDEX IF NOT EXISTS prc_tc_link_ref_idx ON prc_tc_link (ref_code);

COMMENT ON TABLE prc_tc_link IS
    'Связи универсальных моделей из каталога TheCartridge. Перезаливается коллектором '
    'prc-tc-catalog целиком по пришедшим внешним кодам: снятая в ТК связь должна исчезать '
    'и у нас, а не висеть вечно.';
COMMENT ON COLUMN prc_tc_link.ref_code IS
    'Внешним ключом НЕ делаем: связь может указывать на модель, которой в этой выгрузке '
    'ещё нет (её заведут позже), и терять такую ссылку нельзя.';
