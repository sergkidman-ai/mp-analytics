-- Журнал разбора записок из dropbox-бота (@Pro_Dropbox_bot).
--
-- Зачем отдельная таблица, а не «смотреть, есть ли событие с таким dedup_key». Записка может
-- быть СОЗНАТЕЛЬНО не заведена в дневник (поручение «сообщи, когда закончится товар» — это
-- задача, а не событие бизнеса), и такой отказ надо помнить: иначе следующий проход заведёт
-- её снова. Плюс файлы в dropbox живут 7 дней (invoice_bot/cleanup_inbox.py), а журнал
-- остаётся — по нему видно, что приёмник видел и что с этим сделал.
--
-- Файлы и скриншоты в приёмник НЕ берём: их бросают в бот для сессий, а не для дневника.

CREATE TABLE IF NOT EXISTS diary_inbox (
    fname     text        PRIMARY KEY,           -- имя файла в /opt/mp-analytics/dropbox
    taken_at  timestamptz NOT NULL DEFAULT now(),
    event_id  bigint,                            -- NULL = событие сознательно не заводили
    note      text                               -- почему не завели / чем разобрано
);
