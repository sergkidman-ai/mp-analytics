--
-- Универсальный картридж закрывает не одну нашу позицию: CET141644 продаётся и как TN-328M
-- (товар 4310), и как TN-626M (товар 6827), и таких соответствий бывает больше двух. Одного
-- поля `ms_code` для этого мало — оно про «какой это наш товар», а связь про «каким ещё
-- нашим товарам он подходит». Связь понадобится дальше по цепочке, поэтому храним её сразу.
--
-- Формат — как в одноимённом доп.поле МойСклада (36 карточек заполнены руками, разнобоя нет):
-- номер товара четырьмя цифрами с ведущими нулями, разделитель «;», без пробелов —
-- «0027», «0027;0060», «0053;0813;0217;1381».

